class Entity:
    def __init__(self, id_: int, x: int, y: int):
        self.id = id_
        self.prev_x = None
        self.prev_y = None
        self.x = x
        self.y = y

class Agent(Entity):
    counter = 0

    def __init__(self, x: int, y: int, dir_: Direction, agent_type: AgentType):
        Agent.counter += 1
        super().__init__(Agent.counter, x, y)
        self.dir = dir_
        self.req_action: Optional[Action] = None
        self.carrying_shelf: Optional[Shelf] = None
        self.canceled_action = None
        self.has_delivered = False
        self.path = None
        self.busy = False
        self.fixing_clash = 0
        self.type = agent_type
        self.target = 0

    def req_location(self, grid_size) -> Tuple[int, int]:
        if self.req_action != Action.FORWARD:
            return self.x, self.y
        elif self.dir == Direction.UP:
            return self.x, max(0, self.y - 1)
        elif self.dir == Direction.DOWN:
            return self.x, min(grid_size[0] - 1, self.y + 1)
        elif self.dir == Direction.LEFT:
            return max(0, self.x - 1), self.y
        elif self.dir == Direction.RIGHT:
            return min(grid_size[1] - 1, self.x + 1), self.y

        raise ValueError(
            f"Direction is {self.dir}. Should be one of {[v for v in Direction]}"
        )

    def req_direction(self) -> Direction:
        wraplist = [Direction.UP, Direction.RIGHT, Direction.DOWN, Direction.LEFT]
        if self.req_action == Action.RIGHT:
            return wraplist[(wraplist.index(self.dir) + 1) % len(wraplist)]
        elif self.req_action == Action.LEFT:
            return wraplist[(wraplist.index(self.dir) - 1) % len(wraplist)]
        else:
            return self.dir

class Shelf(Entity):
    counter = 0

    def __init__(self, x, y):
        Shelf.counter += 1
        super().__init__(Shelf.counter, x, y)
        # Deadline for delivering this shelf when it is a task (a requested shelf).
        # None = no deadline. Loaded/attached externally (see wwm_sim.deadlines);
        # NOT generated by a model yet — just plumbing to carry the value.
        self.deadline = None
        # Reward earned for delivering this task ON TIME (before its deadline).
        # None -> treated as 1.0. Attached externally (see wwm_sim.values).
        self.value = None
        # SLA HARDNESS = per-step value-decay `g` once late (how badly missing hurts).
        # Steep g (~0.90, a cliff) = hard SLA; gentle g (~0.995) = soft order.
        # None -> use the controller's global default. Attached (see wwm_sim.hardness).
        self.hardness = None

class StuckCounter:
    def __init__(self, position: Tuple[int, int]):
        self.position = position
        self.count = 0

    def update(self, new_position: Tuple[int, int]):
        if new_position == self.position:
            self.count += 1
        else:
            self.count = 0
            self.position = new_position

    def reset(self, position=None):
        self.count = 0
        if position:
            self.position = position

class Warehouse(gym.Env):

    metadata = {"render_modes": ["human", "rgb_array"]}

    def __init__(
        self,
        shelf_columns: int,
        column_height: int,
        shelf_rows: int,
        num_agvs: int,
        num_pickers: int,
        request_queue_size: int,
        max_inactivity_steps: Optional[int],
        max_steps: Optional[int],
        reward_type: RewardType,
        normalised_coordinates: bool=False,
        observation_type: str = "global",
        column_width: int = 2,
        highway_lanes: int = 2,
        n_stations: Optional[int] = None,
    ):
        """The robotic warehouse environment

        Creates a grid world where multiple agents (robots)
        are supposed to collect shelfs, bring them to a goal
        and then return them.
        .. note:
            The grid looks like this:

            shelf
            columns
                vv
            ----------
            -XX-XX-XX-        ^
            -XX-XX-XX-  Column Height
            -XX-XX-XX-        v
            ----------
            -XX----XX-   <\
            -XX----XX-   <- Shelf Rows
            -XX----XX-   </
            ----------
            ----GG----

            G: is the goal positions where agents are rewarded if
            they bring the correct shelfs.

            The final grid size will be
            height: (column_height + 1) * shelf_rows + 2
            width: (2 + 1) * shelf_columns + 1

            The bottom-middle column will be removed to allow for
            robot queuing next to the goal locations

        :param shelf_columns: Number of columns in the warehouse
        :type shelf_columns: int
        :param column_height: Column height in the warehouse
        :type column_height: int
        :param shelf_rows: Number of columns in the warehouse
        :type shelf_rows: int
        :param num_agvs: Number of spawned and controlled agv
        :type num_agvs: int
        :param num_pickers: Number of spawned and controlled pickers
        :type num_pickers: int
        :param request_queue_size: How many shelfs are simultaneously requested
        :type request_queue_size: int
        :param max_inactivity: Number of steps without a delivered shelf until environment finishes
        :type max_inactivity: Optional[int]
        :param reward_type: Specifies if agents are rewarded individually or globally
        :type reward_type: RewardType
        :param observation_type: Specifies type of observations
        :type normalised_coordinates: str
        :param normalised_coordinates: Specifies whether absolute coordinates should be normalised
            with respect to total warehouse size
        :type normalised_coordinates: bool
        """

        self.goals: List[Tuple[int, int]] = []

        self.num_agvs = num_agvs
        self.num_pickers = num_pickers
        self.num_agents = num_agvs + num_pickers

        self._cfg_column_width, self._cfg_highway_lanes = column_width, highway_lanes
        self._cfg_n_stations = n_stations
        self._make_layout_from_params(shelf_columns, shelf_rows, column_height)
        # If no Pickers are generated, AGVs can perform picks independently
        if num_pickers > 0:
            self._agent_types = [AgentType.AGV for _ in range(num_agvs)] + [AgentType.PICKER for _ in range(num_pickers)]
        else:
            self._agent_types = [AgentType.AGENT for _ in range(self.num_agents)]

        self.max_inactivity_steps: Optional[int] = max_inactivity_steps
        self.reward_type = reward_type
        self._cur_inactive_steps = None
        self._cur_steps = 0
        self.max_steps = max_steps

        self.action_size = len(self.action_id_to_coords_map) + 1
        self.action_space = spaces.Tuple(tuple(self.num_agents * [spaces.Discrete(self.action_size)]))

        self.observation_space_mapper = observation_map[observation_type](
            self.num_agvs,
            self.num_pickers,
            self.grid_size,
            len(self.action_id_to_coords_map)-len(self.goals),
            normalised_coordinates,
        )
        self.observation_space = spaces.Tuple(tuple(self.observation_space_mapper.ma_spaces))

        self.request_queue_size = request_queue_size
        self.request_queue = []
        self.rack_groups = find_sections(list([loc for loc in self.action_id_to_coords_map.values() if (loc[1], loc[0]) not in self.goals]))
        self.agents: List[Agent] = []
        self.stuck_counters = []
        self.renderer = None

    @property
    def targets_agvs(self):
        return [agent.target for agent in self.agents[:self.num_agvs]]

    @property
    def targets_pickers(self):
        return [agent.target for agent in self.agents[self.num_agvs:]]

    def _make_layout_from_params(self, shelf_columns: int, shelf_rows: int, column_height: int) -> None:
        assert shelf_columns % 2 == 1, "Only odd number of shelf columns is supported"
        # GEOMETRY (2026-08-06). These two were hardcoded at 2, giving 2-wide pod blocks separated by
        # 2-cell lanes everywhere -> only **31% storage utilisation**, i.e. 69% of the floor is open
        # aisle. Real Kiva-style pod fields run at **~65%** with clusters of 3x6/3x7/4x6/4x7 pods and
        # NARROW one-way lanes, because robots drive under the pods and do not need human-width aisles
        # (pod ~1x1 m, drive unit 75x60 cm -- so our 1 m cell and one-robot-per-cell are both correct).
        # A floor that is 69% open aisle makes congestion trivially avoidable and one-cell debris free
        # to route around, which plausibly contributes to the disturbance nulls.
        # Defaults preserve the existing maps exactly; `column_width=4, highway_lanes=1, column_height=6`
        # reproduces a 4x6 Kiva cluster at ~69% storage.
        self._bottom_rows = 2
        self._highway_lanes = int(getattr(self, "_cfg_highway_lanes", 2) or 2)
        self.column_width = int(getattr(self, "_cfg_column_width", 2) or 2)
        self.column_height = column_height
        self.grid_size = (
            self._highway_lanes + (self.column_height + self._highway_lanes) * shelf_rows  + self._bottom_rows + 1,
            self._highway_lanes + (self.column_width  + self._highway_lanes) * shelf_columns,
        )
        self.grid = np.zeros((len(CollisionLayers), *self.grid_size), dtype=np.int32)

        def get_highway_lanes_indices(axis_size, step):
            return [
                i + j
                for i in range(
                    0, axis_size, step + self._highway_lanes
                )
                for j in range(self._highway_lanes)
            ]

        highway_ys = get_highway_lanes_indices(self.grid_size[0], self.column_height)
        highway_xs = get_highway_lanes_indices(self.grid_size[1], self.column_width)

        def highway_func(x, y):
            return x in highway_xs or y in highway_ys or y >= self.grid_size[0] - 1 - self._bottom_rows

        self.goals = [
            (i, self.grid_size[0] - 1)
            for i in range(self.grid_size[1]) if not i in highway_xs
        ]
        # STATION COUNT (2026-08-06). Station count was an ACCIDENT of the layout -- every non-highway
        # cell on the bottom row became a pick station, giving 10 (large) / 20 (dense). Throughput
        # balance says an 8-AGV fleet needs only **1.2-2.3**: ~52 deliveries per 500-step episode ->
        # ~468 pods/hour, ~1.5 orders/pod -> ~700 picks/hour, against a station rate of 300-600
        # picks/hour. So stations were over-provisioned ~5-10x and COULD NOT bottleneck -- which is
        # very likely why the value-loss autopsy attributes 75% of loss to picker wait: with stations
        # always free, the handoff is the only place a robot can queue.
        # Reducing stations is the right lever; ADDING ROBOTS is not -- saturating 10 stations needs
        # ~35-70 AGVs, which on ~290 lane cells is ~24% occupancy, i.e. gridlock long before stations
        # bind. `n_stations` evenly subsamples the bottom row. None = legacy (all of them).
        _ns = getattr(self, "_cfg_n_stations", None)
        if _ns and 0 < int(_ns) < len(self.goals):
            _ns = int(_ns)
            _step = len(self.goals) / float(_ns)
            self.goals = [self.goals[min(len(self.goals) - 1, int(round(i * _step)))] for i in range(_ns)]
        self.num_goals = len(self.goals)

        self.highways = np.zeros(self.grid_size, dtype=np.int32)
        self.lane_dy = self.lane_dx = None      # filled by _build_lane_directions once highways exist
        self.action_id_to_coords_map = {i+1: (x, y) for i, (y, x) in enumerate(self.goals)}
        item_loc_index=len(self.action_id_to_coords_map)+1
        for x in range(self.grid_size[1]):
            for y in range(self.grid_size[0]):
                self.highways[y, x] = highway_func(x, y)
                if not highway_func(x, y) and (x, y) not in self.goals:
                    self.action_id_to_coords_map[item_loc_index] = (y, x)
                    item_loc_index+=1
        self._build_lane_directions()

    def _is_highway(self, x: int, y: int) -> bool:
        return self.highways[y, x]

    def _build_lane_directions(self):
        """ONE-WAY LANES (2026-08-06). Real robotic pod fields run one-way lanes between clusters --
        that is what makes 1 m aisles viable, because head-on conflicts are designed out rather than
        resolved. Without it, a dense map with 1-cell bidirectional lanes is HARSHER than reality:
        two robots meeting nose-to-nose in a lane with no passing place is a failure mode real
        warehouses do not have.
        Alternating Manhattan scheme: consecutive highway columns run +y / -y, consecutive highway
        rows run +x / -x. Intersections (cell is on both a highway row and column) stay omnidirectional
        so robots can always turn. 0 = unconstrained."""
        H, W = self.grid_size
        self.lane_dy = np.zeros((H, W), dtype=np.int8)     # +1 = may only move down, -1 = only up
        self.lane_dx = np.zeros((H, W), dtype=np.int8)     # +1 = only right,          -1 = only left
        hx = sorted({x for x in range(W) if self.highways[:, x].all()})
        hy = sorted({y for y in range(H) if self.highways[y, :].all()})
        for i, x in enumerate(hx):
            self.lane_dy[:, x] = 1 if i % 2 == 0 else -1
        for j, y in enumerate(hy):
            self.lane_dx[y, :] = 1 if j % 2 == 0 else -1
        for y in hy:                                       # intersections: free to turn
            for x in hx:
                self.lane_dy[y, x] = 0
                self.lane_dx[y, x] = 0

    def _astar_directed(self, cost, start, goal):
        """A* honouring lane directions. `pyastar2d` scores NODES, so it cannot express a one-way
        edge; this is a small heapq search over the same cost grid with the direction test applied per
        move. The grid is ~650 cells, so the Python cost is irrelevant next to the rollout."""
        import heapq
        H, W = cost.shape
        dy_ok, dx_ok = self.lane_dy, self.lane_dx
        g = {start: 0.0}
        h = lambda p: abs(p[0] - goal[0]) + abs(p[1] - goal[1])
        pq = [(h(start), start)]
        came = {}
        while pq:
            _, cur = heapq.heappop(pq)
            if cur == goal:
                out = [cur]
                while cur in came:
                    cur = came[cur]; out.append(cur)
                return out[::-1]
            cy, cx = cur
            for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                ny, nx = cy + dy, cx + dx
                if not (0 <= ny < H and 0 <= nx < W):
                    continue
                c = cost[ny, nx]
                if not np.isfinite(c):
                    continue
                if (ny, nx) != goal:                       # the goal is always enterable
                    if dy and dy_ok[ny, nx] and dy_ok[ny, nx] != dy:
                        continue
                    if dx and dx_ok[ny, nx] and dx_ok[ny, nx] != dx:
                        continue
                ng = g[cur] + float(c)
                if ng < g.get((ny, nx), float("inf")):
                    g[(ny, nx)] = ng
                    came[(ny, nx)] = cur
                    heapq.heappush(pq, (ng + h((ny, nx)), (ny, nx)))
        return None

    def _priority_rank(self):
        """Planning order for prioritized cooperative A*. Rank 0 plans first and yields to nobody.

        WHY THIS IS REQUIRED, not a refinement: without an ordering every robot respects every other
        robot's reservations SYMMETRICALLY, and a stationary robot reserves its own cell for the whole
        horizon. So A waits for B while B waits for A -- "everybody waits" is a perfectly consistent
        solution to the constraint system, and A* finds it because waiting is cheap. Measured on the
        unordered version: seed 14 AGV 3 stood still for 488 of 500 steps with NOTHING blocking it,
        every plan beginning with a wait, and 37 carrying AGVs frozen across 24 seeds (vs 0 without
        space-time at all). Ordering breaks the symmetry: the top-priority robot always has a free
        plan, so somebody always moves.

        `env.st_priority`: 'deadline' = earliest deadline first (EDF), 'valuerate' = highest
        value-per-remaining-step first. A robot with no task ranks last -- it has no claim on a lane.
        """
        mode = getattr(self, "st_priority", "deadline")

        def key(a):
            sh = self._task_of(a)
            if sh is None:
                return (1, 0.0, a.id)                     # no task -> lowest priority
            if mode == "valuerate":
                v = getattr(sh, "value", None)
                v = 1.0 if v is None else float(v)
                T = max(1.0, float(len(getattr(a, "path", None) or [])))
                return (0, -v / T, a.id)                  # highest value rate first
            dl = getattr(sh, "deadline", None)
            return (0, 1e18 if dl is None else float(dl), a.id)   # earliest deadline first

        return {a.id: i for i, a in enumerate(sorted(self.agents, key=key))}

    def _reservations(self):
        """(cell_res, edge_res) for the whole fleet, rebuilt once per step.

        `care_for_agents=True` marks every cell that currently holds a robot as blocked -- a SNAPSHOT.
        A* then plans as though those robots were shelves, so a robot three cells ahead and moving away
        is routed around like a rack. Measured cost (seed 11, picker 13): a picker 6-10 steps from its
        goal was thrown 30-46 steps away, three times, +90 steps of detour, while the AGV it was
        committed to waited 138 steps. The wall it detoured around had walked off two ticks later.

        Every robot already publishes its full `path`, so occupancy is knowable as a function of TIME:
        robot r is at path[i] at t=i+1. Reserving (cell, t) lets a planner ask "will this cell be busy
        when I ARRIVE" instead of "is it busy now".

        cell_res[(y, x, t)] = agent id;  edge_res[((y1,x1), (y2,x2), t)] = agent id, meaning that agent
        traverses y1,x1 -> y2,x2 arriving at t. Edge reservations forbid two robots swapping through
        each other, which cell reservations alone permit.

        A robot's FINAL cell is reserved for every remaining t in the window: once it arrives it stays
        there, and treating it as free is the mistake that makes plans collide with parked robots.
        """
        now = int(self._cur_steps)
        if getattr(self, "_res_key", None) == now:
            return self._res_cell, self._res_edge
        W = int(getattr(self, "st_window", 16))
        cell, edge = {}, {}
        for a in self.agents:
            cells = [(a.y, a.x)]
            for (px, py) in (getattr(a, "path", None) or []):
                cells.append((py, px))
            for i, c in enumerate(cells[:W + 1]):
                cell[(c[0], c[1], i)] = a.id
            for i in range(1, min(len(cells), W + 1)):
                edge[(cells[i - 1], cells[i], i)] = a.id
            last = cells[-1]
            for i in range(len(cells), W + 1):
                cell[(last[0], last[1], i)] = a.id     # it parks there and stays
        self._res_key, self._res_cell, self._res_edge = now, cell, edge
        self._res_rank = self._priority_rank()
        return cell, edge

    def _spacetime_astar(self, grid, start, goal, agent):
        """A* over (y, x, t) against the reservation table. `grid` carries the STATIC costs only
        (shelves / highway restrictions / disturbances / congestion), with inf for impassable.

        Waiting in place is a legal action -- that is the whole point: holding one tick to let a robot
        pass is almost always cheaper than routing around it, and the snapshot planner cannot express
        it. Beyond `st_window` reservations are ignored, so the search degenerates gracefully to plain
        A* on the far side of the horizon rather than failing.
        """
        import heapq
        W = int(getattr(self, "st_window", 16))
        cap = int(getattr(self, "st_max_expand", 30000))
        cell_res, edge_res = self._reservations()
        me = agent.id
        H, Wd = grid.shape
        sy, sx = int(start[0]), int(start[1])
        gy, gx = int(goal[0]), int(goal[1])

        def h(y, x):
            return abs(y - gy) + abs(x - gx)

        rank = getattr(self, "_res_rank", None) or {}
        myrank = rank.get(me, 0)

        def yields_to(owner):
            """Do I have to respect this reservation? Only if its owner outranks me. Without this the
            constraint system admits the all-wait fixed point (see `_priority_rank`)."""
            return owner is not None and owner != me and rank.get(owner, 0) < myrank

        def blocked(y, x, t):
            if t > W:
                return False                       # past the horizon: unknown, treat as free
            return yields_to(cell_res.get((y, x, t)))

        openq = [(h(sy, sx), 0.0, sy, sx, 0)]
        best = {(sy, sx, 0): 0.0}
        came = {}
        expand = 0
        while openq:
            _f, g, y, x, t = heapq.heappop(openq)
            if g > best.get((y, x, t), 1e18):
                continue
            if (y, x) == (gy, gx):
                path = [(y, x)]
                cur = (y, x, t)
                while cur in came:
                    cur = came[cur]
                    path.append((cur[0], cur[1]))
                path.reverse()
                return path
            expand += 1
            if expand > cap:
                return None
            nt = t + 1
            for dy, dx in ((0, 0), (1, 0), (-1, 0), (0, 1), (0, -1)):
                ny, nx = y + dy, x + dx
                if not (0 <= ny < H and 0 <= nx < Wd):
                    continue
                step = 1.0 if (dy == 0 and dx == 0) else float(grid[ny, nx])
                if step == float("inf"):
                    continue
                if blocked(ny, nx, nt):
                    continue
                # edge swap: another robot crossing (ny,nx) -> (y,x) as I cross the other way
                if nt <= W and yields_to(edge_res.get(((ny, nx), (y, x), nt))):
                    continue
                ng = g + step
                if ng < best.get((ny, nx, nt), 1e18):
                    best[(ny, nx, nt)] = ng
                    came[(ny, nx, nt)] = (y, x, t)
                    heapq.heappush(openq, (ng + h(ny, nx), ng, ny, nx, nt))
        return None

    def find_path(self, start, goal: Tuple[int], agent: Tuple[int], care_for_agents: bool = True) -> List[Tuple[int]]:
        """
        Constructs a path from start to goal using the A* algorithm contidioned on a grid that integrates both the
        environment specific (shelf) and the presence of other agents as obstacles.

        If `care_for_agents` is True, the grid is adjusted to consider other agents as obtacles. However, we avoid
        situatiosns where the paths is invalidated by agents of other types waiting to cooperate with the current.
        For Pickers, the grid is further modified to ensure they can only travel through designated highways and
        access goal locations.

        Parameters:
        - care_for_agents (bool): Whether to consider other agents in the grid.
        - agent (Agent): The agent for which the path is being calculated.
        - start (tuple): The starting coordinates (x, y) of the agent.
        - goal (tuple): The goal coordinates (x, y) for the agent.

        Returns:
        - List of tuples representing the path from start to goal, or an empty list if no path is found.
        """
        grid = np.zeros(self.grid_size)
        # SPACE-TIME (opt-in `env.spacetime_reservations`): robots are NOT baked into the obstacle map;
        # they enter the search as (cell, time) reservations instead, so a cell someone is vacating is
        # passable at the moment I reach it.
        _st = bool(getattr(self, "spacetime_reservations", False)) and care_for_agents
        if care_for_agents and not _st:
            grid += self.grid[CollisionLayers.AGVS]
            grid += self.grid[CollisionLayers.PICKERS]
        # Agents should start a path regardless if some others are waiting around the target location
        grid[goal[0], goal[1]] = 0

        if agent.type == AgentType.PICKER:
            # Pickers can only travel through the highway, but can access goal locations
            grid += (1-self.highways)
            grid[goal[0], goal[1]] -= not self._is_highway(goal[1], goal[0])
            # SIDE ACCESS (opt-in `env.picker_side_access`, USER RULE 2026-08-09: "absolutely no
            # reason the picker should keep the AGV waiting -- it can access from the side").
            # Only the goal pod itself was ever unblocked, so a pod's walkable NEIGHBOURS stayed
            # walled and most pods had exactly ONE legal doorway (their single adjacent lane cell).
            # Measured worst case (seed 144): picker 9 stood in pod (10,17)'s only doorway while
            # picker 10 -- committed to that pod -- faced it from two cells up the one-wide lane;
            # each picker's doorway lay PAST the other, a swap is impossible in a 1-wide lane, the
            # clash replan found no alternative because there WAS none, and the AGV at the pod
            # waited 448 of 500 steps. Opening the rack face beside the goal gives every pod up to
            # four doorways, so a single blocker can no longer seal a rendezvous.
            # Robots still block (collision layers add on top); only the static highway wall is
            # lifted, and only for the cells adjacent to THIS query's goal.
            if getattr(self, "picker_side_access", False):
                for _dy, _dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    _yy, _xx = goal[0] + _dy, goal[1] + _dx
                    if 0 <= _yy < self.grid_size[0] and 0 <= _xx < self.grid_size[1]:
                        grid[_yy, _xx] -= not self._is_highway(_xx, _yy)
            for i in range(self.grid_size[1]):
                grid[self.grid_size[0] - 1, i] = 1

        # Ban Pickers crossing through racks if adjacent target location is chosen and force them thake the long way around.
        start_fix = (0, 0)
        if agent.type == AgentType.PICKER and  ((not self._is_highway(start[1], start[0])) and goal[0] == start[0] and abs(goal[1] - start[1]) == 1):
            if self._is_highway(start[1] - 1, start[0]):
                start_fix = (0, - 1)
            if self._is_highway(start[1] + 1, start[0]):
                start_fix = (0, 1)
            grid[start[0], start[1]] = 1

        grid[start[0]+start_fix[0], start[1]+start_fix[1]] = 0
        # DISTURBANCES: random temporary blockages (unpredictable). Treat as obstacles so every
        # path (initial + reroute) routes around them. Never block the agent's own start/goal.
        #
        # CLAIRVOYANCE (2026-08-05): `self.disturbed` is GROUND TRUTH, so by default every planner
        # routes around every blockage the instant it spawns — including cells no robot has ever
        # been near. That is why realistic debris measures ~0% cost: the fleet never ENCOUNTERS a
        # disturbance, so there is nothing to learn and nothing for a belief map to recover.
        # With `env.use_belief_routing`, planning instead uses what the fleet has OBSERVED
        # (line-of-sight limited, decaying) while EXECUTION still hits ground truth — so a robot
        # discovers a blockage by running into it, reroutes, and publishes. That collision between
        # plan and reality is the "one robot's pain -> fleet knowledge" event M2 claims.
        # Robot plans stay globally shared (a route is a data structure; broadcasting it is free);
        # only disturbances are occluded (a dropped item is a fact about the floor — someone must
        # look). Information in a computer is shareable; information in the world must be sensed.
        if getattr(self, "use_belief_routing", False) and getattr(self, "rumor_map", None) is not None:
            _dist = self.rumor_map.believed_blocked(getattr(self, "b_hard", 0.5))
        else:
            _dist = getattr(self, "disturbed", None)
        if _dist:
            _sfy, _sfx = start[0] + start_fix[0], start[1] + start_fix[1]
            for (_dy, _dx) in _dist:
                if (_dy, _dx) != (goal[0], goal[1]) and (_dy, _dx) != (start[0], start[1]) \
                        and (_dy, _dx) != (_sfy, _sfx):
                    grid[_dy, _dx] = 9      # nonzero -> obstacle after the != 0 conversion below
        grid = [list(map(int, l)) for l in (grid!=0)]
        grid = np.array(grid, dtype=np.float32)
        grid[np.where(grid == 1)] = np.inf
        grid[np.where(grid == 0)] = 1
        # ROUTE ADHERENCE: if the agent carries a committed route (Part A's chosen route) and this
        # env prefers it, make OFF-route free cells cost more than ON-route ones. A* then hugs the
        # committed route and only detours around an actual blocker, rejoining ASAP -- it reroutes,
        # but keeps to the chosen route. (pyastar2d needs weights >= 1, so we penalise off-route
        # rather than discount on-route.) No effect unless prefer_committed is set + cells attached.
        free = (grid == 1)
        # never modify the start cell(s) -- the env's start-strip keys off grid[start] > 1
        free[start[0], start[1]] = False
        free[start[0] + start_fix[0], start[1] + start_fix[1]] = False
        # CONGESTION: add the forecast traffic map to free-cell costs, so paths (initial AND
        # reroute) steer around cells other robots are predicted to occupy. congestion_grid is
        # set by the planner each step; weight 0 / grid None -> no effect.
        cong = getattr(self, "congestion_grid", None)
        wcong = getattr(self, "congestion_weight", 0.0)
        if cong is not None and wcong:
            grid[free] = grid[free] + wcong * cong[free]
        # ADHERENCE: off-committed-route free cells cost an extra bit, so A* hugs the chosen route
        # and only detours around a real blocker, rejoining ASAP. (Composes with congestion above.)
        # SOFT RISK TERM (M2 letter, Part A step 5; built 2026-08-23): graded belief-weighted
        # path cost on cells suspicious-but-below-the-hard-threshold. NOTE: under the shipped
        # reset-mode map with b_hard=0.5 this band is EMPTY by construction (reset beliefs are
        # near-binary: dirty-seen stays >0.5 until seen clean and is hard-excluded; clean/unknown
        # sits at or below the prior) -- the term only becomes live if b_hard is tuned upward.
        wrisk = getattr(self, "belief_risk_w", 0.0)
        if wrisk and getattr(self, "use_belief_routing", False)                 and getattr(self, "rumor_map", None) is not None:
            _b = self.rumor_map.belief()
            _soft = np.clip(_b - 0.5, 0.0, None).astype(np.float32)
            _soft[_b > getattr(self, "b_hard", 0.5)] = 0.0   # hard-excluded already
            grid[free] = grid[free] + wrisk * _soft[free]
        # SCOUT DETOURS (user 2026-08-23): the weighted pick between "shortest path" and "path
        # that also looks at suspicious ground". No dedicated scout robots -- working robots tilt
        # toward corridors whose line-of-sight sweeps hazard-prone, evidence-starved cells. Cost
        # semantics: an uninformative free cell costs up to +scout_weight extra, a max-information
        # cell +0, so A* accepts a detour of ~k extra steps only when it buys ~k/scout_weight
        # cells' worth of looking at learned hot zones. Composes with congestion + adherence.
        wsc = getattr(self, "scout_weight", 0.0)
        _rm = getattr(self, "rumor_map", None)
        if wsc and _rm is not None and getattr(_rm, "learn_style", False)                 and getattr(self, "use_belief_routing", False):
            if getattr(self, "_scout_cache_t", -1) != int(self._cur_steps):
                self._scout_cache_t = int(self._cur_steps)
                _G = _rm.info_gain_map(self)
                _gm = float(_G.max())
                self._scout_cache = (1.0 - _G / _gm).astype(np.float32) if _gm > 0 else None
            if self._scout_cache is not None:
                grid[free] = grid[free] + wsc * self._scout_cache[free]
        cc = getattr(agent, "committed_cells", None)
        if getattr(self, "prefer_committed", False) and cc:
            off = free.copy()
            for (yy, xx) in cc:
                if 0 <= yy < grid.shape[0] and 0 <= xx < grid.shape[1]:
                    off[yy, xx] = False
            grid[off] = grid[off] + (_OFF_ROUTE_COST - 1.0)
        if _st:
            _p = self._spacetime_astar(grid, tuple(np.add(start, start_fix)), tuple(goal), agent)
            if _p:
                # A space-time plan contains explicit WAIT steps (the cell repeats), but a path here is
                # a list of cells to traverse one per tick -- there is no wait cell, and
                # `get_next_micro_action` raises KeyError on a zero delta. Collapse repeats and keep the
                # SPATIAL route: the waiting still happens, because a blocked robot NOOPs on its own.
                # What we wanted from the search was the route that does not detour around robots who
                # will have moved, and that survives the collapse intact.
                # KEEP THE WAITS. Collapsing repeats discards the SCHEDULE that made the plan safe:
                # "reach A at t=3, wait one, enter B at t=5" becomes "A then B", so the robot enters B
                # at t=4 -- exactly when the reservation table said it was occupied. The search solves a
                # scheduling problem; throwing away the schedule leaves only a shorter route and none of
                # the safety. Measured with the collapse: -0.81% to -1.45%, and pod-waiting UP.
                # A repeated cell is consumed as a NOOP in `attribute_macro_actions`.
                _c = list(_p)
                # Same start-strip rule as the snapshot planner below. The PICKER start-fix plans from
                # a cell ADJACENT to where the robot actually stands (it blocks the true start to stop
                # pickers cutting through racks), so that first cell is a real move and must be kept.
                # Dropping it unconditionally leaves path[0] two cells from the agent -- a diagonal
                # delta, and `get_next_micro_action` raises KeyError on those.
                return [(x, y) for y, x in _c[1 - int(grid[start[0], start[1]] > 1):]]
            # no reservation-respecting route inside the horizon: fall back to the snapshot planner
            # rather than returning nothing, so behaviour is never WORSE than before.
            grid = grid.copy()
            for _a in self.agents:
                if _a.id != agent.id and (_a.y, _a.x) != (goal[0], goal[1]):
                    grid[_a.y, _a.x] = np.inf
            grid[np.add(start, start_fix)[0], np.add(start, start_fix)[1]] = 1.0
        if getattr(self, "one_way", False) and getattr(self, "lane_dy", None) is not None:
            astar_path = self._astar_directed(grid, tuple(np.add(start, start_fix)), tuple(goal))
        else:
            astar_path = pyastar2d.astar_path(grid, np.add(start, start_fix), goal, allow_diagonal=False) # returns None if cant find path
        # astar_path = astar_path[int(np.where(astar_path == np.add(start, start_fix))[0][0]):]
        if astar_path is not None:
            astar_path = [tuple(x) for x in list(astar_path)] # convert back to other format
            astar_path = astar_path[1 - int(grid[start[0], start[1]] > 1):]

        if astar_path:
            return [(x, y) for y, x in astar_path]
        else:
            return []

    def _recalc_grid(self) -> None:
        self.grid.fill(0)

        carried_shelf_ids = {agent.carrying_shelf.id for agent in self.agents if agent.carrying_shelf}
        for shelf in self.shelfs:
            if shelf.id not in carried_shelf_ids:
                self.grid[CollisionLayers.SHELVES, shelf.y, shelf.x] = shelf.id
        for agent in self.agents:
            layer = CollisionLayers.PICKERS if agent.type == AgentType.PICKER else CollisionLayers.AGVS
            self.grid[layer, agent.y, agent.x] = agent.id
            if agent.carrying_shelf:
                 self.grid[CollisionLayers.CARRIED_SHELVES, agent.y, agent.x] = agent.carrying_shelf.id

    def get_carrying_shelf_information(self):
        return [agent.carrying_shelf != None for agent in self.agents[:self.num_agvs]]

    def get_shelf_request_information(self) -> np.ndarray[int]:
        request_item_map = np.zeros(len(self.shelfs))
        requested_shelf_ids = [shelf.id for shelf in self.request_queue]
        for id_, coords in self.action_id_to_coords_map.items():
            if (coords[1], coords[0]) not in self.goals:
                if self.grid[CollisionLayers.SHELVES, coords[0], coords[1]] in requested_shelf_ids:
                    request_item_map[id_ - len(self.goals) - 1] = 1
        return request_item_map

    def get_empty_shelf_information(self) -> np.ndarray[int]:
        empty_item_map = np.zeros(len(self.shelfs))
        for id_, coords in self.action_id_to_coords_map.items():
            if (coords[1], coords[0]) not in self.goals:
                if self.grid[CollisionLayers.SHELVES, coords[0], coords[1]] == 0 and (
                    self.grid[CollisionLayers.CARRIED_SHELVES, coords[0], coords[1]] == 0
                    or self.agents[
                        self.grid[CollisionLayers.AGVS, coords[0], coords[1]] - 1
                    ].req_action
                    not in [Action.NOOP, Action.TOGGLE_LOAD]
                ):
                    empty_item_map[id_ - len(self.goals) - 1] = 1
        return empty_item_map

    def attribute_macro_actions(self, macro_actions: List[int]) -> Tuple[int, int]:
        agvs_distance_travelled = 0
        pickrs_distance_travelled = 0
        # Logic for Macro Actions
        for agent, macro_action in zip(self.agents, macro_actions):
            # Initialize action for step
            agent.req_action = Action.NOOP
            # STATION HEADWAY (opt-in `env.station_headway`). Keep the approach cell to an OCCUPIED
            # station clear, so a robot on the station can always pull out.
            # VERIFIED failure this prevents (seed 1, dense map): AGV 5 sat ON station (17,24) trying
            # to leave via (18,24); AGV 1 sat on (18,24) trying to enter (17,24). Nose-to-nose at the
            # station mouth, neither able to move, with AGVs 6/7/8 stacked behind wanting the same
            # station -- for 425 consecutive steps -- while stations (1,24) and (9,24) stood empty.
            # A swap needs a third cell to resolve and there is none in a 1-cell lane, so the only
            # cure is not to close the gap in the first place. Arrivals therefore hold one cell back
            # while the station is occupied; the exit stays open and the queue drains.
            # EXIT-ROUTE INVARIANT (opt-in `env.require_exit`). Never move into a cell that has no way
            # out. A robot may only advance if its target cell still has at least one FREE neighbour
            # besides the cell it is leaving -- i.e. it always keeps an escape.
            # WHY: measured on seed 13, the fleet froze COMPLETELY at t=392 -- zero robots moved for
            # 108 consecutive steps, every AGV carrying a pod, each one's next cell occupied by
            # another. A deadlock breaks when somebody steps aside, but a LOADED AGV cannot: its pod
            # can only go down at a station, and the station is what is blocked. With all 8 loaded
            # there was no free robot left to open a gap, so nothing could ever move again.
            # The cure is not to let the last gap close. Robots hold one step short instead of
            # sealing themselves in, which costs a little throughput and makes the freeze impossible.
            # NB only `req_action` is touched, never `path` -- rewriting a path mid-step desynchronises
            # position from path (that trap has bitten four times in this file).
            if (getattr(self, "require_exit", False) and agent.path and len(agent.path) > 1):
                _tx, _ty = agent.path[0]
                _hold = False
                for _g in self.goals:                              # only the cells AROUND a station
                    if abs(_g[0] - _tx) + abs(_g[1] - _ty) != 1:
                        continue
                    if not self.grid[CollisionLayers.AGVS, _g[1], _g[0]]:
                        continue                                   # station empty, nobody to trap
                    _esc = 0
                    for _dx, _dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        _ax, _ay = _g[0] + _dx, _g[1] + _dy
                        if not (0 <= _ay < self.grid_size[0] and 0 <= _ax < self.grid_size[1]):
                            continue
                        if (_ax, _ay) == (_tx, _ty):
                            continue                               # this is the cell I am about to take
                        if not self._is_highway(_ax, _ay):
                            continue
                        if self.grid[CollisionLayers.AGVS, _ay, _ax] or \
                           self.grid[CollisionLayers.PICKERS, _ay, _ax]:
                            continue
                        _esc += 1
                    if _esc == 0:                                  # taking this cell seals the station in
                        _hold = True
                        break
                if _hold:
                    agent.req_action = Action.NOOP
                    continue
            # STATION EXIT PRIORITY (opt-in `env.station_exit_priority`, 2026-08-08).
            # The seed-13 deadlock is NOT a blocked warehouse -- it is a robot refusing an open door.
            # At t=400 AGV 1 stood on station (5,24) with its path insisting on exit cell (5,23), held
            # by AGV 7 which wanted the station. Cells (4,24) and (6,24) were BOTH FREE the whole time
            # (their claimants were correctly held back by the headway rule), but AGV 1 never
            # considered them: `find_path` was run once, and a robot only replans when the stuck
            # counter trips. So the two sat nose-to-nose for 100 steps and five more AGVs queued behind.
            # The station occupant is the one robot that MUST move -- everyone else is waiting on it --
            # so give it first claim on any free neighbour: replan around the blocker, and if no route
            # exists, sidestep to any free cell. Either way the station frees and the queue drains.
            # NB the new path is adopted but the robot sits out THIS tick (`req_action = NOOP`):
            # `_execute_forward` reads the move from `req_action` and pops from `path`, so handing a
            # new path to a robot that may still move desynchronises the two (this trap has bitten
            # four times in this file). It walks the new route from the next tick.
            if (getattr(self, "station_exit_priority", False) and agent.type == AgentType.AGV
                    and (agent.x, agent.y) in self.goals and agent.path):
                _bx, _by = agent.path[0]
                _blocked = self.grid[CollisionLayers.AGVS, _by, _bx]
                if _blocked and _blocked != agent.id:
                    _goal = (agent.path[-1][1], agent.path[-1][0])
                    _new = self.find_path((agent.y, agent.x), _goal, agent)
                    _ok = (_new and abs(_new[0][0] - agent.x) + abs(_new[0][1] - agent.y) == 1
                           and not self.grid[CollisionLayers.AGVS, _new[0][1], _new[0][0]])
                    if _ok:
                        agent.path = _new
                    else:
                        # No route around the blocker: step aside onto ANY free neighbour. Clearing the
                        # station matters more than making progress; the route is rebuilt from there.
                        # Escape directions: flanks always; UP as well when `keepout_top` is on.
                        # The original horizontal-only restriction existed because the sidestep once
                        # PREPENDED a cell without rebuilding the route (vertical step -> diagonal
                        # continuation -> KeyError). The continuation has been rebuilt from the
                        # sidestep cell ever since, so the restriction is a leftover; with the top
                        # cell now policed as a side cell, it is also a legal escape.
                        _dirs = ((1, 0), (-1, 0), (0, -1)) if getattr(self, "keepout_top", False) \
                            else ((1, 0), (-1, 0))
                        for _dx, _dy in _dirs:
                            _ax, _ay = agent.x + _dx, agent.y + _dy
                            if not (0 <= _ay < self.grid_size[0] and 0 <= _ax < self.grid_size[1]):
                                continue
                            if self.grid[CollisionLayers.AGVS, _ay, _ax]:
                                continue
                            # Rebuild the REST of the route from the sidestep cell. Prepending the
                            # sidestep to the existing path leaves [sidestep, old_first], and those two
                            # are diagonal whenever the sidestep is perpendicular to the old heading --
                            # `get_next_micro_action` maps only unit steps and raises KeyError on a
                            # diagonal (it did, immediately, on the first run of this rule).
                            _cont = self.find_path((_ay, _ax), _goal, agent, care_for_agents=False)
                            agent.path = [(_ax, _ay)] + list(_cont or [])
                            break
                    agent.req_action = Action.NOOP
                    continue
            # BLOCKED REPLAN (opt-in `env.blocked_replan`, 2026-08-08). The station-exit rule fixed the
            # seed-13 deadlock -- a robot insisting on a blocked cell while a free one sat beside it --
            # but it only helps the robot standing ON a station. The same refusal happens mid-corridor:
            # measured 194 permanently-frozen carrying AGVs across 144 episodes, with 51% of episodes
            # containing at least one. So apply the principle everywhere: an AGV whose next cell has
            # been held by another AGV for `blocked_patience` steps replans AROUND it
            # (care_for_agents=True) instead of waiting on a blocker that is itself waiting.
            # No sidestep here -- only a full A* route, which is continuous by construction.
            if (getattr(self, "blocked_replan", False) and agent.type == AgentType.AGV and agent.path):
                _bx, _by = agent.path[0]
                _occ = self.grid[CollisionLayers.AGVS, _by, _bx]
                if not hasattr(self, "_blocked_for"):
                    self._blocked_for = {}
                if _occ and _occ != agent.id:
                    self._blocked_for[agent.id] = self._blocked_for.get(agent.id, 0) + 1
                else:
                    self._blocked_for[agent.id] = 0
                if self._blocked_for.get(agent.id, 0) >= int(getattr(self, "blocked_patience", 8)):
                    _goal = (agent.path[-1][1], agent.path[-1][0])
                    _new = self.find_path((agent.y, agent.x), _goal, agent)
                    if (_new and abs(_new[0][0] - agent.x) + abs(_new[0][1] - agent.y) == 1
                            and not self.grid[CollisionLayers.AGVS, _new[0][1], _new[0][0]]):
                        agent.path = _new
                        self._blocked_for[agent.id] = 0
                        agent.req_action = Action.NOOP     # walk the new route from the next tick
                        continue
            # NO-SEAL-IN (opt-in `env.station_no_seal`, 2026-08-08). The headway rule above keeps
            # BYSTANDERS off an occupied station's approach cells, but it never checks the robot doing
            # the ENTERING: `len(agent.path) > 1` deliberately exempts the final approach ("never block
            # a final approach"), so an AGV may always step onto a station -- even when every neighbour
            # of that station is already occupied. It then has no way out.
            # VERIFIED (seed 13, t=400-499): AGV 1 sat ON station (5,24) wanting to exit via (5,23);
            # AGV 7 sat on (5,23) wanting to enter (5,24). Nose-to-nose, neither able to move, for 100
            # consecutive steps. AGVs 3/5/6/8 queued behind -- correctly held by headway -- and AGV 2
            # behind them. Seven of eight AGVs frozen holding pods, episode delivered 2 tasks.
            # A loaded AGV cannot step aside (its pod only goes down at a station), so once it is
            # sealed in the deadlock is permanent. The cure is to refuse to enter a cell you cannot
            # leave: an AGV may occupy a station only while that station still has one free neighbour
            # besides the cell it is vacating.
            if (getattr(self, "station_no_seal", False) and agent.path
                    and agent.type == AgentType.AGV
                    and tuple(agent.path[0]) in self.goals):
                _gx, _gy = agent.path[0]
                _esc = 0
                for _dx, _dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    _ax, _ay = _gx + _dx, _gy + _dy
                    if not (0 <= _ay < self.grid_size[0] and 0 <= _ax < self.grid_size[1]):
                        continue
                    if (_ax, _ay) == (agent.x, agent.y):
                        continue                       # the cell I am vacating does not count
                    if self.grid[CollisionLayers.AGVS, _ay, _ax]:
                        continue
                    _esc += 1
                if _esc == 0:
                    agent.req_action = Action.NOOP
                    continue
            # SIDE-CELL KEEPOUT (opt-in `env.station_side_keepout`, USER RULE 2026-08-08:
            # "keep a side cell free -- ALL the time"). The exit-priority rule guarantees the station
            # occupant first claim on a free side cell, but only if a free side cell EXISTS. Headway
            # holds arrivals back only while the station is OCCUPIED -- so robots may take both side
            # cells while a station is momentarily empty, the station refills, and the occupant is
            # sealed in. That is exactly the seed-65 full-fleet freeze under picker_final_step: eight
            # AGVs locked around station (11,24), 99/99 steps blocked, cells (9..13,22..24).
            # The unconditional version: an AGV may not ENTER a station's side cell while the OPPOSITE
            # side cell is occupied. At most one flank is ever taken, so an escape route exists at all
            # times, independent of station state. Transit and single-sided queueing stay legal.
            if (getattr(self, "station_side_keepout", False) and agent.path
                    and agent.type == AgentType.AGV
                    # THE OCCUPANT IS EXEMPT. Keeping a side cell free exists FOR the robot on the
                    # station -- it IS the escape route. Without this exemption the rule pins the
                    # occupant: its exit is a side cell whose opposite flank is taken by the queue, so
                    # the occupant holds forever and the queue behind it never drains. Measured (seed
                    # 139): AGV on station (11,24), next cell FREE on 99/99 steps, never moved.
                    and (agent.x, agent.y) not in self.goals):
                _nx, _ny = agent.path[0]
                _hold = False
                if (_nx, _ny) not in self.goals:
                    for _g in self.goals:
                        if _g[1] == _ny and abs(_g[0] - _nx) == 1:      # side cell of station _g
                            _ox = 2 * _g[0] - _nx                       # the opposite side cell
                            if 0 <= _ox < self.grid_size[1]:
                                if (self.grid[CollisionLayers.AGVS, _g[1], _ox]
                                        or self.grid[CollisionLayers.PICKERS, _g[1], _ox]):
                                    _hold = True
                                    break
                        # TOP SIDE (opt-in `env.keepout_top`, USER RULE 2026-08-13: "side cells for
                        # stations should include the top side"). Stations sit on the bottom row, so
                        # each has THREE neighbours: two flanks plus the cell above. The flank rule
                        # alone lets the escape invariant be defeated from above -- both flanks
                        # policed, top cell freely taken, occupant sealed. Entering the TOP cell is
                        # held when BOTH flanks are already occupied: never take the last free
                        # neighbour of a station.
                        if (getattr(self, "keepout_top", False)
                                and _nx == _g[0] and _ny == _g[1] - 1):
                            _occ_flanks = 0
                            for _fx in (_g[0] - 1, _g[0] + 1):
                                if not (0 <= _fx < self.grid_size[1]):
                                    _occ_flanks += 1        # off-map flank counts as occupied
                                elif (self.grid[CollisionLayers.AGVS, _g[1], _fx]
                                        or self.grid[CollisionLayers.PICKERS, _g[1], _fx]):
                                    _occ_flanks += 1
                            if _occ_flanks == 2:
                                _hold = True
                                break
                if _hold:
                    agent.req_action = Action.NOOP
                    continue
            # SLOT DIVERT (opt-in `env.slot_divert`, 2026-08-09). Same principle as station_divert,
            # applied to the RETURN leg: a carrying AGV on final approach to its drop slot, blocked by
            # another AGV squatting on that slot, has no reason to wait -- the warehouse is full of
            # empty slots. Measured (seed 15): AGV 7 parked on (5,16) permanently while AGV 6 stood
            # one cell away for the last 99 steps of the episode wanting to drop there -- the single
            # frozen instance left under picker_side_access. Blocked >= `slot_patience` steps ->
            # re-pick the nearest OTHER free storage slot and go there instead. NOOP on the adopting
            # tick (the five-times-bitten desync trap).
            if (getattr(self, "slot_divert", False) and agent.type == AgentType.AGV
                    and agent.carrying_shelf is not None and agent.path
                    and len(agent.path) <= 2):
                _tx, _ty = agent.path[-1]
                if (_tx, _ty) not in self.goals:
                    _sq = self.grid[CollisionLayers.AGVS, _ty, _tx]
                    if not hasattr(self, "_slot_blocked"):
                        self._slot_blocked = {}
                    if _sq and _sq != agent.id:
                        self._slot_blocked[agent.id] = self._slot_blocked.get(agent.id, 0) + 1
                    else:
                        self._slot_blocked[agent.id] = 0
                    if self._slot_blocked.get(agent.id, 0) >= int(getattr(self, "slot_patience", 8)):
                        _goalset = {tuple(g) for g in self.goals}
                        # charger cells are not drop slots when a battery model is active (an
                        # opt-in keepout set the controller may attach; empty -> unchanged)
                        _chgko = getattr(self, "charger_keepout", ()) or ()
                        _best, _bd = None, 1 << 30
                        for (_yy, _xx) in self.action_id_to_coords_map.values():
                            if ((_xx, _yy) in _goalset or (_xx, _yy) == (_tx, _ty)
                                    or (_xx, _yy) in _chgko):
                                continue
                            if self.grid[CollisionLayers.SHELVES, _yy, _xx]:
                                continue
                            if (self.grid[CollisionLayers.AGVS, _yy, _xx]
                                    or self.grid[CollisionLayers.PICKERS, _yy, _xx]):
                                continue
                            _d = abs(agent.x - _xx) + abs(agent.y - _yy)
                            if _d and _d < _bd:
                                _best, _bd = (_xx, _yy), _d
                        if _best is not None:
                            _np = self.find_path((agent.y, agent.x), (_best[1], _best[0]), agent)
                            if not _np:
                                _np = self.find_path((agent.y, agent.x), (_best[1], _best[0]), agent,
                                                     care_for_agents=False)
                            if _np and abs(_np[0][0] - agent.x) + abs(_np[0][1] - agent.y) == 1:
                                agent.path = _np
                                self._slot_blocked[agent.id] = 0
                                agent.req_action = Action.NOOP
                                continue
            # STATION DIVERT (opt-in `env.station_divert`, USER RULE 2026-08-08: "if when you get
            # there two or more AGVs are already waiting, go to the next nearest station"). Checked on
            # final approach (<= 6 cells out) with a 10-step cooldown so a robot does not flip-flop
            # between stations. NB the new path is adopted but the robot sits out THIS tick
            # (`req_action = NOOP`): `_execute_forward` reads the move from `req_action` and pops from
            # `path`, so rewriting a path on a robot that may still move desynchronises the two -- that
            # trap has bitten five times in this file.
            if (getattr(self, "station_divert", False) and agent.type == AgentType.AGV
                    and agent.carrying_shelf is not None and agent.path):
                _gx, _gy = agent.path[-1]
                if ((_gx, _gy) in self.goals and len(agent.path) <= 6
                        and self._cur_steps - getattr(agent, "_divert_t", -99) >= 10):
                    _near = 0
                    for _a in self.agents:
                        if (_a.id != agent.id and _a.type == AgentType.AGV
                                and _a.carrying_shelf is not None
                                and abs(_a.x - _gx) + abs(_a.y - _gy) <= 2):
                            _near += 1
                    if _near >= 2:
                        _alts = [g for g in self.goals if g != (_gx, _gy)]
                        if _alts:
                            _alt = min(_alts, key=lambda g: abs(agent.x - g[0]) + abs(agent.y - g[1]))
                            _np = self.find_path((agent.y, agent.x), (_alt[1], _alt[0]), agent)
                            if not _np:
                                _np = self.find_path((agent.y, agent.x), (_alt[1], _alt[0]), agent,
                                                     care_for_agents=False)
                            if _np and abs(_np[0][0] - agent.x) + abs(_np[0][1] - agent.y) == 1:
                                agent.path = _np
                                agent._divert_t = self._cur_steps
                                agent.req_action = Action.NOOP
                                continue
            if (getattr(self, "station_headway", False) and agent.path
                    and agent.type == AgentType.AGV and len(agent.path) > 1):
                _nx, _ny = agent.path[0]
                _hold = False
                if (_nx, _ny) not in self.goals:                          # never block a final approach
                    for _g in self.goals:
                        if abs(_g[0] - _nx) + abs(_g[1] - _ny) == 1:      # this cell is a station mouth
                            _occ = self.grid[CollisionLayers.AGVS, _g[1], _g[0]]
                            if _occ and _occ != agent.id:                 # station busy -> keep exit clear
                                _hold = True
                                break
                if _hold:
                    agent.req_action = Action.NOOP
                    continue
            # STATION SERVICE: the pod is being picked from; this robot is held at the station and is
            # not fleet capacity until the dwell expires (see process_shelf_deliveries).
            if getattr(self, "_service_until", None) and \
                    self._service_until.get(agent.id, 0) > self._cur_steps:
                continue
            # DEBRIS RECOVERY HOLD (M2 enforcement, opt-in env.debris_hold_steps>0): a robot that
            # drove into a disturbed cell is immobilized while it recovers -- the first time debris
            # has an EXECUTION-layer existence (before this, `disturbed` was planning-only and the
            # measured "cost of ignorance" was pure avoidance overhead; see paper SS5.16).
            if getattr(agent, "_debris_hold", 0) > 0:
                agent._debris_hold -= 1
                agent.req_action = Action.NOOP
                continue
            # UNTIL-AMNESTY mode (USER DESIGN 2026-08-19: "when you hit it you spin your treads
            # UNTIL amnesty"): stuck for as long as the debris persists under you -- the collision
            # cost IS the hazard's remaining lifetime. Released the tick the cell is cleaned.
            if getattr(agent, "_debris_stuck", False):
                if (agent.y, agent.x) in getattr(self, "disturbed", ()):
                    agent.req_action = Action.NOOP
                    continue
                agent._debris_stuck = False
            # Collision avoidance logic
            if agent.fixing_clash > 0:
                agent.fixing_clash -= 1
            if not agent.busy:
                agent.target = 0
                if macro_action != 0:
                    # STUCK-AWARE REPATH (opt-in `env.stuck_avoid_agents`, 2026-08-08). The stuck
                    # counter releases a jammed agent with `busy = False` -- but the repath below runs
                    # with `care_for_agents=False`, so A* ignores every robot and hands back the SAME
                    # blocked route. The agent re-enters the identical deadlock at once and the release
                    # accomplishes nothing. An agent that was just released routes AROUND robots
                    # instead, falling back to the agent-blind route only if no such route exists.
                    _avoid = (getattr(self, "stuck_avoid_agents", False)
                              and agent.id in getattr(self, "_recently_stuck", ()))
                    if _avoid:
                        agent.path = self.find_path((agent.y, agent.x), self.action_id_to_coords_map[macro_action], agent)
                        self._recently_stuck.discard(agent.id)
                        if not agent.path:
                            agent.path = self.find_path((agent.y, agent.x), self.action_id_to_coords_map[macro_action], agent, care_for_agents=False)
                    else:
                        agent.path = self.find_path((agent.y, agent.x), self.action_id_to_coords_map[macro_action], agent, care_for_agents=False)
                    if agent.path:
                        agent.busy = True
                        agent.target = macro_action
                        agent.req_action = get_next_micro_action(agent.x, agent.y, agent.dir, agent.path[0])
                        self.stuck_counters[agent.id - 1].reset((agent.x, agent.y))
            else:
                # Check if agent finished the given path, if not continue the path
                if agent.path == []:
                    if agent.type in [AgentType.AGV, AgentType.AGENT]:
                        agent.req_action = Action.TOGGLE_LOAD
                    if agent.type == AgentType.PICKER:
                        agent.busy = False
                elif tuple(agent.path[0]) == (agent.x, agent.y):
                    # A PLANNED WAIT from the space-time planner: the next cell IS this cell. Hold for
                    # one tick and consume it. `get_next_micro_action` maps only unit deltas and raises
                    # KeyError on (0,0), which is why the plan cannot simply be walked.
                    agent.req_action = Action.NOOP
                    agent.path = agent.path[1:]
                else:
                    agent.req_action = get_next_micro_action(agent.x, agent.y, agent.dir, agent.path[0])
                    agvs_distance_travelled += int(agent.type == AgentType.AGV)
                    pickrs_distance_travelled += int(agent.type == AgentType.PICKER)
                if len(agent.path) == 1:
                    # If agent is at the end of a path and carrying a shelf and the target location is already occupied, restart agent
                    if agent.carrying_shelf and self.grid[CollisionLayers.SHELVES, agent.path[-1][1], agent.path[-1][0]]:
                        agent.req_action = Action.NOOP
                        agent.busy = False
                    # Logic for Pickers to load shelves if AGV is present at location or wait otherwise
                    if agent.type == AgentType.PICKER:
                        # PICKER GOES IN (`env.picker_final_step`, USER RULE 2026-08-08).
                        # Stock protocol: a picker one cell from its rendezvous HOLDS until the AGV is
                        # already there AND requesting TOGGLE_LOAD -- measured, that is 594 of 691
                        # final-step moments spent waiting outside the pod. So the picker arrives, stops
                        # short, and the handshake cannot start until the AGV shows up; both robots then
                        # spend a step syncing. Stepping in early instead means the picker is ALREADY on
                        # the pod when the AGV lands, so the load fires immediately.
                        # (This is where the final step is decided -- NOT the referee. An earlier
                        # attempt to fix it in `resolve_move_conflict` was inert because 86% of these
                        # pickers are NOOPed here, before the referee ever sees them.)
                        _go_in = getattr(self, "picker_final_step", False)
                        if _go_in and not self.grid[CollisionLayers.PICKERS,
                                                    agent.path[-1][1], agent.path[-1][0]]:
                            pass                      # walk onto the pod and wait there
                        elif (
                            self.grid[CollisionLayers.AGVS, agent.path[-1][1], agent.path[-1][0]] == 0
                            or self.agents[self.grid[CollisionLayers.AGVS, agent.path[-1][1], agent.path[-1][0]]- 1].req_action != Action.TOGGLE_LOAD
                        ):
                            agent.req_action = Action.NOOP
                        elif (
                            self.grid[CollisionLayers.AGVS, agent.path[-1][1], agent.path[-1][0]] != 0
                            and self.agents[self.grid[CollisionLayers.AGVS, agent.path[-1][1], agent.path[-1][0]] - 1].req_action == Action.TOGGLE_LOAD
                            ):
                            self.stuck_counters[agent.id - 1].reset((agent.x, agent.y))
        return agvs_distance_travelled, pickrs_distance_travelled

    # --- priority-ordered commit (2026-08-05) ---------------------------------
    # The legacy resolver commits only graph cycles + ONE dag_longest_path per weakly-connected
    # component, then NOOPs everything else (see the blanket `failed_agents` loop below). Measured:
    # a picker emitted FORWARD -> NOOP on 144 of 183 steps with its target cell EMPTY on all three
    # collision layers. Nothing was blocking it; it was silenced by construction.
    # This variant instead walks movers in PRIORITY order and commits each one whose target is free
    # or is being vacated by an already-committed agent, iterating to a fixpoint so follow-the-leader
    # chains resolve. Cycles (pure rotations, which never have a free cell to seed them) are still
    # seeded by the legacy cycle detection; 2-cycles (swaps) stay forbidden as physically impossible.
    # Set `env.commit_priority` to 'value' | 'deadline' | 'arbitrary' to enable. None = legacy.
    def _sim_eta(self, me, my_path, horizon=25):
        """Predicted steps for `me` to finish `my_path`, simulating EVERY robot forward along its
        PUBLISHED path (USER DESIGN 2026-08-10: at a collision point, be aware of the trajectories of
        whatever blocks you -- and of whoever will block you along the way).

        This uses trajectories for EVALUATION, not constraint. The two prior attempts failed in
        opposite ways: space-time reservations used them as CONSTRAINTS ("cell claimed at t+3,
        forbidden") and found the everybody-waits fixed point; clash_choose used NO trajectory model
        ("blocker clears in 1 tick") and its clearance term measurably never influenced the decision.
        Here nothing is forbidden -- both options are simply scored by simulated arrival time, and a
        wrong prediction degrades an estimate instead of freezing a robot.

        The simulation is a deterministic cellular walk: each tick, every robot advances one cell
        along its published route if the cell is free, iterated to a fixpoint within the tick so
        follow-the-leader chains resolve -- D moves, freeing C, freeing B, freeing me (the "sequence
        of four pickers" cascade). Robots with no path are parked and never move: exactly the
        pessimism the clash_choose estimate lacked. Turning costs are ignored, which biases both
        options equally. Beyond `horizon` the remaining route is charged at face value.
        """
        pos, rem = {}, {}
        for a in self.agents:
            pos[a.id] = (a.x, a.y)
            rem[a.id] = list(my_path or []) if a.id == me.id else list(a.path or [])
        t = 0
        while t < horizon:
            if not rem[me.id]:
                return t
            t += 1
            occ = set(pos.values())
            moved_ids = set()
            progressed = True
            while progressed:
                progressed = False
                for a in self.agents:
                    r = rem[a.id]
                    if not r or a.id in moved_ids:
                        continue
                    nxt = (r[0][0], r[0][1])
                    if nxt == pos[a.id]:
                        r.pop(0)                      # planned wait consumed
                        moved_ids.add(a.id)
                        progressed = True
                        continue
                    if nxt in occ:
                        continue
                    occ.discard(pos[a.id])
                    occ.add(nxt)
                    pos[a.id] = nxt
                    r.pop(0)
                    moved_ids.add(a.id)
                    progressed = True
        return horizon + len(rem[me.id])

    def _task_of(self, agent):
        sh = agent.carrying_shelf
        if sh is None and agent.path:
            x, y = agent.path[-1]
            sid = self.grid[CollisionLayers.SHELVES, y, x]
            if sid:
                sh = self.shelfs[sid - 1]
        return sh

    def _commit_key(self, agent, mode):
        if mode == "arbitrary":
            return (0.0, agent.id)
        sh = self._task_of(agent)
        if sh is None:
            return (-1e18, agent.id)          # no task -> lowest priority, ties by id
        if mode == "value":
            return (1.0 if getattr(sh, "value", None) is None else float(sh.value), agent.id)
        dl = getattr(sh, "deadline", None)
        return (-(1e17 if dl is None else float(dl)), agent.id)   # earliest deadline first

    def _utility(self, agent):
        """Combined value + deadline importance, mirroring the controller's own tier score
        (`_deadline_score` = v + URG_W * max(0, 1 - spare/URG_S0), URG_W=8, URG_S0=40).
        A robot with no task has no claim on the corridor."""
        sh = self._task_of(agent)
        if sh is None:
            return -1e18
        v = 1.0 if getattr(sh, "value", None) is None else float(sh.value)
        dl = getattr(sh, "deadline", None)
        if dl is None:
            return v
        spare = float(dl) - float(self._cur_steps)
        return v + 8.0 * max(0.0, 1.0 - spare / 40.0)

    def _prioritized_reroute(self, agent, other):
        """PRIORITIZED REROUTE (`env.prioritized_reroute`). On an impending collision BOTH robots
        replan, ordered by utility: the higher-utility robot replans FIRST and so gets the unconstrained
        pick of route; the lower-utility robot replans SECOND, by which time the winner's new path is
        already committed and is treated as an obstacle.

        This is deliberately NOT the yield rule measured on 2026-08-05 (-5.71 value / -6.45 deadline).
        There only the LOSER rerouted while the winner kept its path, so the same robots were denied
        over and over, accumulated delay, and crossed their own deadlines -- textbook starvation. Here
        the loser still receives a route, it is merely planned second, so that mechanism should not fire.
        Returns True if it handled the pair."""
        hi, lo = (agent, other) if self._utility(agent) >= self._utility(other) else (other, agent)
        # BOTH robots must sit out the tick on which they replan. `_execute_forward` derives the MOVE
        # from `req_action` but pops the PATH -- so handing a new route to a robot already committed to
        # move this tick desynchronises its position from its path, and the following step asks for a
        # cell two squares away (KeyError in `get_next_micro_action`). Freeze both, then replan.
        hi.req_action = Action.NOOP
        lo.req_action = Action.NOOP
        for who in (hi, lo):
            if not who.path:
                continue
            goal = (who.path[-1][1], who.path[-1][0])
            new_path = self.find_path((who.y, who.x), goal, who)
            if new_path == []:
                new_path = self.find_path((who.y, who.x), goal, who, care_for_agents=False)
            # A replan is only usable if its first cell is ADJACENT to where the robot actually is --
            # `get_next_micro_action` maps a one-cell delta to a turn/forward and raises KeyError on
            # anything else. Reject non-adjacent replans and keep the existing path.
            if new_path and abs(new_path[0][0] - who.x) + abs(new_path[0][1] - who.y) == 1:
                who.path = new_path
        lo.req_action = Action.NOOP          # winner moves this tick; loser re-enters next tick
        lo.fixing_clash = _FIXING_CLASH_TIME
        return True

    def _staleness(self, agent):
        """Steps since this robot last got CLOSER to its own goal than it has ever been.

        The path-freeze defect is that nothing guarantees progress. Every reroute decision is local and
        instantaneous, and nobody counts how often a robot has been displaced, so the same robot can be
        bounced indefinitely. Measured on picker 13 (seed 11), distance to a fixed goal over 139 steps:
            10 -> 20 -> 46 -> 35 -> 21 -> 9 -> 30 -> 18 -> 13 -> 1
        while the AGV it was committed to waited 138 steps. It moved on 78% of steps the whole time.

        Staleness is the starvation signal: a robot that keeps being sent away never improves on its
        best distance, so its counter climbs without bound, while a robot making normal progress keeps
        resetting to 0. Recomputed once per step for the whole fleet and cached.
        """
        now = int(self._cur_steps)
        if getattr(self, "_stale_key", None) != now:
            self._stale_key = now
            best = getattr(self, "_best_dist", {})
            goal = getattr(self, "_stale_goal", {})
            since = getattr(self, "_stale_since", {})
            for a in self.agents:
                path = getattr(a, "path", None)
                if not path:
                    best.pop(a.id, None)
                    goal.pop(a.id, None)
                    since[a.id] = 0
                    continue
                g = (path[-1][0], path[-1][1])
                d = abs(a.x - g[0]) + abs(a.y - g[1])
                if goal.get(a.id) != g:            # new task: the old best is meaningless
                    goal[a.id] = g
                    best[a.id] = d
                    since[a.id] = 0
                elif d < best.get(a.id, 1 << 30):
                    best[a.id] = d
                    since[a.id] = 0                # genuine progress
                else:
                    since[a.id] = since.get(a.id, 0) + 1
            self._best_dist, self._stale_goal, self._stale_since = best, goal, since
        return self._stale_since.get(agent.id, 0)

    def _yields_to(self, agent, other):
        """Does `agent` yield (reroute around `other`) in a clash? Higher priority gets first choice
        of route; the loser is the one that reroutes. Without this the rerouter is whoever the nested
        clash loop reaches first, which can flip between steps -- both robots reroute, re-collide, and
        dance indefinitely. `env.commit_priority` selects the ranking; None = legacy iteration order."""
        # PROGRESS AGING (opt-in `env.progress_aging`). Under the legacy rule below, whoever the loop
        # reaches FIRST yields -- arbitrary, and nothing prevents the same robot yielding forever. That
        # is the starvation mechanism behind the path freeze. Rank by staleness instead: the robot that
        # has gone longest without improving on its best distance outranks everyone, so the others
        # route around IT. Unlike forcing a designated yielder to move, this changes only WHO yields --
        # it never pushes a robot into occupied space, so it should not carry the peak penalty that
        # `require_reroute` did (peak t=-2.00). Ties fall through to the legacy behaviour.
        if getattr(self, "progress_aging", False):
            _sa, _so = self._staleness(agent), self._staleness(other)
            if _sa != _so:
                return _sa < _so                          # the more starved robot holds its route
        mode = getattr(self, "commit_priority", None)
        if not mode:
            return True                                   # legacy: first-reached reroutes
        return self._commit_key(agent, mode) < self._commit_key(other, mode)

    def resolve_move_conflict(self, agent_list):
        commited_agents = set()
        G = nx.DiGraph()
        for agent in agent_list:
            start = agent.x, agent.y
            target = agent.req_location(self.grid_size)
            # SELF-LOOP FIX (2026-08-05). `req_location()` returns the agent's OWN cell whenever it is
            # not moving forward, so every stationary agent used to add a self-loop edge. `find_cycle`
            # then reported a CYCLE(len 1) for the whole weakly-connected component, the cycle branch
            # committed only the agents named in that self-loop, and `dag_longest_path` NEVER RAN --
            # so every genuinely-moving agent in the component was silenced by the `failed_agents`
            # sweep below. ONE PARKED ROBOT POISONED ITS ENTIRE COMPONENT.
            # It was also self-sustaining: a silenced agent is stationary next step, so it re-creates
            # the self-loop that silences it -- which is why a robot that stopped once never restarted.
            # Measured on 8x6 day-list seed 3, picker 11: CYCLE / not-on-longest-path / silenced on
            # 320 of 320 frozen steps, with its target cell EMPTY.
            # CAREFUL -- the self-loop was doing TWO jobs: poisoning cycle detection (bad) and keeping
            # stationary-but-ACTING agents inside `commited_agents` (essential). `req_location()`
            # returns the own cell for ANY non-FORWARD action, including TOGGLE_LOAD, so simply
            # dropping the edge made those agents fall into `failed_agents` and get NOOPed -- no robot
            # could load or unload a shelf and freezes went 1.5 -> 13.7 per episode. So: keep them out
            # of the graph, but commit them directly. A stationary agent is not a movement conflict; it
            # still occupies its cell for the occupancy checks below and in the executor.
            if start != target:
                G.add_edge(start, target)
            else:
                commited_agents.add(agent.id)
        wcomps = [G.subgraph(c).copy() for c in nx.weakly_connected_components(G)]
        for comp in wcomps:
            try:
                # if we find a cycle in this component we have to
                # commit all nodes in that cycle, and nothing else
                cycle = nx.algorithms.find_cycle(comp)
                if len(cycle) == 2:
                    # [A] <-> [B] head-on swap: physically impossible, so the PAIR cannot move.
                    # SWAP-CASCADE FIX (2026-08-07). `continue` used to skip the WHOLE COMPONENT, so a
                    # single blocked pair silenced every robot connected to them -- and since the swap
                    # never resolves, the same component re-forms every step forever. Measured on the
                    # stall (seed 1, dense map): **91% of components hit this branch**, 100% of
                    # would-be movers were silenced, and nothing moved for 440 steps with 39 orders
                    # open. Dense 1-cell bidirectional lanes generate head-on swaps constantly, which
                    # is why this only became fatal on the realistic map.
                    # Now: drop the two swapping cells and re-evaluate the REST of the component, so
                    # one blocked pair no longer freezes its neighbours.
                    # DEADLOCK BREAKER (opt-in `env.deadlock_backoff`). A head-on swap is refused every
                    # step and NOTHING resolves it: measured on seed 1, AGVs (1,5,6,7,8) held the same
                    # mutual block for 425 consecutive steps until the episode ended with 39 orders
                    # open. The referee is right that the swap is impossible; the missing piece is that
                    # no robot ever BACKS OFF. So once a pair has been blocked for `deadlock_patience`
                    # steps, force the lower-priority one (fewest steps invested, tie-break by id) to
                    # retreat to a free neighbouring cell, opening the lane for the other.
                    if getattr(self, "deadlock_backoff", False):
                        key = tuple(sorted([cycle[0][0], cycle[0][1]]))
                        if not hasattr(self, "_swap_age"): self._swap_age = {}
                        self._swap_age[key] = self._swap_age.get(key, 0) + 1
                        if self._swap_age[key] >= int(getattr(self, "deadlock_patience", 5)):
                            here = {(a.x, a.y): a for a in self.agents}
                            pair = [here[c] for c in key if c in here]
                            if len(pair) == 2:
                                loser = min(pair, key=lambda a: (len(a.path or []), -a.id))
                                occupied = set(here)
                                for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
                                    nx_, ny_ = loser.x + dx, loser.y + dy
                                    if (0 <= ny_ < self.grid_size[0] and 0 <= nx_ < self.grid_size[1]
                                            and (nx_, ny_) not in occupied and self._is_highway(nx_, ny_)):
                                        # SIT OUT THIS TICK. `_execute_forward` derives the MOVE from
                                        # `req_action` but pops the PATH, so giving a new path to a
                                        # robot that may still move desynchronises the two and the next
                                        # step asks for a non-adjacent cell (KeyError in
                                        # `get_next_micro_action`). This trap has bitten four times in
                                        # this codebase; freeze first, walk the new path next tick.
                                        loser.path = [(nx_, ny_)] + list(loser.path or [])
                                        loser.req_action = Action.NOOP
                                        commited_agents.add(loser.id)
                                        self._swap_age[key] = 0
                                        self._deadlock_breaks = getattr(self, "_deadlock_breaks", 0) + 1
                                        break
                    if getattr(self, "swap_isolate", False):
                        stuck = {cycle[0][0], cycle[0][1]}
                        rest = comp.subgraph([n for n in comp.nodes if n not in stuck]).copy()
                        for sub in [rest.subgraph(c).copy() for c in nx.weakly_connected_components(rest)]:
                            try:
                                c2 = nx.algorithms.find_cycle(sub)
                                nodes = [e[0] for e in c2] if len(c2) != 2 else []
                            except nx.NetworkXNoCycle:
                                nodes = nx.algorithms.dag_longest_path(sub)
                            for (nx_, ny_) in nodes:
                                aid = self.grid[CollisionLayers.AGVS, ny_, nx_]
                                if aid: commited_agents.add(aid); continue
                                pid = self.grid[CollisionLayers.PICKERS, ny_, nx_]
                                if pid: commited_agents.add(pid)
                    continue
                for edge in cycle:
                    start_node = edge[0]
                    agent_id = self.grid[CollisionLayers.AGVS, start_node[1], start_node[0]]
                    # action = self.agents[agent_id - 1].req_action
                    # print(f"{agent_id}: C {cycle} {action}")
                    if agent_id > 0:
                        commited_agents.add(agent_id)
                        continue
                    picker_id = self.grid[CollisionLayers.PICKERS, start_node[1], start_node[0]]
                    if picker_id > 0:
                        commited_agents.add(picker_id)
                        continue
            except nx.NetworkXNoCycle:
                longest_path = nx.algorithms.dag_longest_path(comp)
                for x, y in longest_path:
                    agent_id = self.grid[CollisionLayers.AGVS, y, x]
                    if agent_id:
                        commited_agents.add(agent_id)
                        continue
                    picker_id = self.grid[CollisionLayers.PICKERS, y, x]
                    if picker_id:
                        commited_agents.add(picker_id)
        clashes = 0
        self.clash_pairs_this_step = []  # (agent.id, other.id) for each reroute this step
        for agent in agent_list:
            for other in agent_list:
                if agent.id != other.id:
                    agent_new_x, agent_new_y = agent.req_location(self.grid_size)
                    other_new_x, other_new_y = other.req_location(self.grid_size)
                    # Clash fixing logic
                    if agent.path and ((agent_new_x, agent_new_y) in [(other.x, other.y), (other_new_x, other_new_y)]):
                        # If we are in a rack and one of the agents is a picker we ignore clashses, assumed behaviour is Picker is loading
                        if not self._is_highway(agent_new_x, agent_new_y) and (agent.type == AgentType.PICKER or other.type == AgentType.PICKER) and agent.type != other.type:
                            # Allow Pickers to step over AGVs (if no other Picker at that shelf location) or AGVs to step over Pickers (if no other AGV at that shelf location)
                            if ((agent.type == AgentType.PICKER and self.grid[CollisionLayers.PICKERS, agent_new_y, agent_new_x] in [0, agent.id])
                                or (agent.type == AgentType.AGV and self.grid[CollisionLayers.AGVS, agent_new_y, agent_new_x] in [0, agent.id])):
                                commited_agents.add(agent.id)
                                continue
                        # If the agent's next action bumps it into another agent
                        if (agent_new_x, agent_new_y) == (other.x, other.y):
                            if getattr(self, "prioritized_reroute", False) and agent.path and other.fixing_clash == 0:
                                clashes += 1
                                self.clash_pairs_this_step.append((agent.id, other.id))
                                self._prioritized_reroute(agent, other)
                                continue
                            agent.req_action = Action.NOOP # Stop the action
                            # Check if the clash is not solved naturaly by the other agent moving away
                            if (other_new_x, other_new_y) in [(agent.x, agent.y), (agent_new_x, agent_new_y)] and not other.req_action in (Action.LEFT, Action.RIGHT):
                                # MANDATORY REROUTE (2026-08-05, `env.require_reroute`): baseline
                                # rerouting is best-effort -- it is skipped entirely when the other
                                # robot is already fixing (so on a mutual clash NOBODY reroutes), and
                                # it silently gives up when find_path returns empty, leaving the robot
                                # to NOOP and re-clash next step. That is the endless dance. When the
                                # flag is set the designated yielder MUST produce a route: the
                                # already-fixing gate is dropped, and an agent-avoiding replan that
                                # fails falls back to a plain replan so a route always exists.
                                _required = getattr(self, "require_reroute", False)
                                # ENCOUNTER HYSTERESIS (opt-in `env.clash_hysteresis`, USER DIAGNOSIS
                                # 2026-08-10: "they do a flip flop before they even collide"). This
                                # branch fires on IMPENDING conflict, a tick before contact, and both
                                # robots are eligible to replan on successive ticks -- A curves around
                                # B, B then curves around A's new path, both re-approach, repeat: the
                                # dance, and the engine of the residual orbit livelock (seed 134's
                                # 92-step wait: the committed picker closed to 3 cells and was thrown
                                # back out to 6, four times, while moving the whole time).
                                # Fix: the FIRST robot of a pair to replan OWNS the replanning for the
                                # next `clash_hysteresis` ticks (default 20); its partner holds course.
                                # One dancer leads. Both keep MOVING -- nobody is told to wait -- so
                                # this is not rationing, it is removing the mutual-adaptation loop.
                                _dance_ok = True
                                if getattr(self, "clash_hysteresis", False):
                                    _hyst = int(getattr(self, "clash_hysteresis", 0))
                                    _hyst = _hyst if _hyst > 1 else 20
                                    if not hasattr(self, "_dance"):
                                        self._dance = {}
                                    _dk = (min(agent.id, other.id), max(agent.id, other.id))
                                    _dr = self._dance.get(_dk)
                                    if _dr is not None and _dr[1] > self._cur_steps:
                                        _dance_ok = (_dr[0] == agent.id)
                                    else:
                                        self._dance[_dk] = (agent.id, self._cur_steps + _hyst)
                                if _dance_ok and (_required or other.fixing_clash == 0) and self._yields_to(agent, other):
                                    clashes+=1
                                    self.clash_pairs_this_step.append((agent.id, other.id))
                                    agent.fixing_clash = _FIXING_CLASH_TIME # Agent start time for clash fixing
                                    goal = (agent.path[-1][1], agent.path[-1][0])
                                    new_path = self.find_path((agent.y, agent.x), goal, agent)
                                    if new_path == [] and _required:
                                        new_path = self.find_path((agent.y, agent.x), goal, agent,
                                                                  care_for_agents=False)
                                    # WAIT-vs-REROUTE, ranked by VALUE RATE (opt-in `env.clash_choose`,
                                    # 2026-08-08). `find_path` here runs with care_for_agents=True, so
                                    # every robot is treated as a PERMANENT wall. A robot that will step
                                    # aside in two ticks is routed around as though it were a shelf, and
                                    # because pickers are confined to the sparse highway network,
                                    # "around" means most of the way across the warehouse.
                                    # MEASURED (seed 11, picker 13, committed to the pod where AGV 2
                                    # waited 138 steps): all four of its reroutes came from THIS line,
                                    # each firing as it closed in --
                                    #   t=365 10->30   t=391 10->46   t=438 6->36   t=463 18->22
                                    # Three times it was 6-10 steps from the waiting AGV and was sent
                                    # 30-46 steps away: +90 steps of detour. It walks the detour,
                                    # returns, clashes, repeats. The AGV waited 138 steps.
                                    # Rather than cap the detour with an arbitrary ratio, rank the two
                                    # options the way the planner ranks everything else -- by the value
                                    # rate each achieves, v / T:
                                    #   T_reroute = len(new route)
                                    #   T_wait    = blocker clearance + len(existing route)
                                    # Clearance is cheap and local: a robot holding a path intends to
                                    # move and clears next tick; a parked one clears when its service
                                    # expires; one with neither gets the pessimistic `clash_wait_est`.
                                    # v cancels for a single task, so this reduces to "whichever reaches
                                    # the goal sooner" -- but it is written as a rate because Part B
                                    # needs exactly this comparison to price a support action (wait /
                                    # reroute / yield) against getting on with the task.
                                    # EXACTLY ONE WAITER, chosen by proximity (`env.clash_choose`).
                                    # The first version compared wait-vs-reroute independently for each
                                    # robot, which let BOTH sides of a clash choose "wait": each is near
                                    # its own goal, so each prefers holding its route. Waiting also
                                    # resets `fixing_clash`, so nothing stopped the second robot from
                                    # reaching the same branch and reaching the same conclusion. Result
                                    # was a standoff -- pod-waiting rose 67.5k -> 81k and 18 frozen AGVs
                                    # came back.
                                    # The roles must be assigned jointly, not chosen independently. The
                                    # robot with the SHORTER remaining route waits: it is nearly there,
                                    # so a detour costs it the largest fraction of its trip, while the
                                    # one with further to go absorbs a detour more cheaply and is likely
                                    # to be routed around the obstruction anyway. Ties break by id so
                                    # the two robots always agree on who is waiting -- the predicate is
                                    # antisymmetric, so exactly one of them holds and the other reroutes.
                                    # TRAJECTORY-SIMULATED WAIT-vs-DETOUR (opt-in `env.clash_sim`,
                                    # USER DESIGN 2026-08-10). Score BOTH options by simulated
                                    # arrival time against everyone's published trajectories --
                                    # waiting behind a chain that clears beats a 40-step loop, and
                                    # a detour whose own lane is about to jam loses the credit the
                                    # snapshot gave it. Ties go to the detour: always-reroute is the
                                    # measured-safe reflex, so the simulation must EARN a wait.
                                    if (getattr(self, "clash_sim", False) and new_path
                                            and agent.path):
                                        _h = int(getattr(self, "clash_sim_horizon", 25))
                                        _ew = self._sim_eta(agent, agent.path, _h)
                                        _ed = self._sim_eta(agent, new_path, _h)
                                        # STALENESS HAIRCUT (opt-in `env.clash_sim_haircut`, 2026-08-10):
                                        # trust a "wait" verdict only when the predicted blocking delay
                                        # (simulated ETA minus the route's free-run length) is short.
                                        # Published paths go stale as everyone replans, so a long
                                        # predicted wait rests on predictions that will not survive --
                                        # measured as the max-wait tail fattening 83 -> 92 without it.
                                        _hc = float(getattr(self, "clash_sim_haircut", 0) or 0)
                                        _delay = _ew - len(agent.path)
                                        if _ew < _ed and (not _hc or _delay <= _hc):
                                            new_path = []      # predicted faster to hold the route
                                    if (getattr(self, "clash_choose", False) and new_path
                                            and agent.path):
                                        # Rank on MANHATTAN distance to goal, not path length. Path
                                        # length is not stable within a step: once the first robot of a
                                        # pair reroutes, its path changes, so the second robot compares
                                        # against a different number and the two disagree about who is
                                        # closer -- both then hold. (Measured: both-waited rose 84 ->
                                        # 128 on seed 11 with the path-length version.) Positions do not
                                        # change until execute_micro_actions, so distance-to-goal gives
                                        # both robots the same answer and the predicate stays
                                        # antisymmetric: exactly one waits.
                                        _mg = agent.path[-1]
                                        _mine = abs(agent.x - _mg[0]) + abs(agent.y - _mg[1])
                                        _op = getattr(other, "path", None)
                                        if _op:
                                            _og = _op[-1]
                                            _theirs = abs(other.x - _og[0]) + abs(other.y - _og[1])
                                        else:
                                            _theirs = -1           # no route: it is not going anywhere
                                        # POLARITY (`env.clash_choose` = 'near' | 'far'). 'near' = the
                                        # closer robot holds and the farther one detours (a detour costs
                                        # the nearly-arrived robot the largest fraction of its trip).
                                        # 'far' = the opposite: the robot with further to go holds,
                                        # betting that the one about to arrive should be allowed to
                                        # finish and free its task. Both are plausible; measured.
                                        _far = (getattr(self, "clash_choose", True) in ("far", "stepfar"))
                                        _iam = (_mine > _theirs) if _far else (_mine < _theirs)
                                        if _iam or (_mine == _theirs and agent.id < other.id):
                                            new_path = []          # I hold; the other goes around
                                            # 'step': don't merely HOLD -- take one cell out of the way.
                                            # Holding leaves the pair adjacent, so the clash re-forms
                                            # next step and can re-enter the standoff; that is why the
                                            # 46-step detour was load-bearing despite looking absurd.
                                            # What the detour actually buys is SEPARATION, and
                                            # separation costs one cell, not forty-six. Same trick that
                                            # worked for station exit priority: sidestep, then rebuild
                                            # the route FROM the sidestep cell (prepending it instead
                                            # leaves [sidestep, old_first] diagonal, which no robot can
                                            # execute -- that bug has bitten repeatedly in this file).
                                            if getattr(self, "clash_choose", "") in ("step", "stepfar"):
                                                _blk = {(other.x, other.y)}
                                                _op2 = getattr(other, "path", None)
                                                if _op2:
                                                    _blk.add(tuple(_op2[0]))
                                                for _dx, _dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                                                    _sx, _sy = agent.x + _dx, agent.y + _dy
                                                    if not (0 <= _sy < self.grid_size[0]
                                                            and 0 <= _sx < self.grid_size[1]):
                                                        continue
                                                    if (_sx, _sy) in _blk:
                                                        continue
                                                    if self.grid[CollisionLayers.AGVS, _sy, _sx] or                                                             self.grid[CollisionLayers.PICKERS, _sy, _sx]:
                                                        continue
                                                    _cont = self.find_path((_sy, _sx), goal, agent,
                                                                           care_for_agents=False)
                                                    new_path = [(_sx, _sy)] + list(_cont or [])
                                                    break
                                    if new_path != []: # If the agent can find an alternative path, assign it if not let the other solve the clash
                                        agent.path = new_path
                                    else:
                                        agent.fixing_clash = 0
                        elif (agent_new_x, agent_new_y) == (other_new_x, other_new_y) and (agent_new_x, agent_new_y) != (agent.x, agent.y):
                            # If the agent's next action bumps it into another agent position after they take actions simultaneously
                            if agent.fixing_clash == 0 and other.fixing_clash == 0:
                                agent.req_action = Action.NOOP # If the agent's actions leads them in the position of another STOP
                                agent.fixing_clash = _FIXING_CLASH_TIME  # Agent wait one step while the other moves into place

        commited_agents = set([self.agents[id_ - 1] for id_ in commited_agents])
        # PICKER FREE MOVE (opt-in `env.picker_free_move`, USER RULE 2026-08-08).
        # If a picker's next cell is clear, it moves. Full stop -- one boolean, no graph reasoning.
        # WHY: the blanket sweep below NOOPs every agent the graph machinery did not name, and pickers
        # are the usual casualty. Measured earlier this session: a picker emitted FORWARD -> NOOP on
        # 144 of 183 steps with its target cell EMPTY on all three collision layers. It was silenced by
        # construction, not by any obstacle -- and a silenced picker is stationary next step, which is
        # what keeps an AGV parked at a pod waiting for it.
        # Only claims a cell nobody committed to this tick, so it cannot create a collision.
        if getattr(self, "picker_free_move", False):
            taken = {a.req_location(self.grid_size) for a in commited_agents}
            _committed_only = (getattr(self, "picker_free_move", False) == "committed")
            for agent in agent_list:
                # AGV FREE MOVE (opt-in `env.agv_free_move`, 2026-08-09). The same sweep pathology the
                # picker rule cures, observed on an AGV: seed 92, AGV 1 carrying to station (11,24),
                # requesting FORWARD into (10,7) -- FREE on both layers -- and NOOPed by the referee
                # 100/100 consecutive steps. The legacy resolver commits only graph cycles plus one
                # dag_longest_path per component and silences everyone else, so an agent whose branch
                # is never chosen starves indefinitely with nothing in its way. Committing a move into
                # a free, unclaimed cell cannot create a collision (same guard as the picker rule).
                # The committed-only rendezvous gate below is picker-specific and skipped for AGVs.
                _is_agv_move = (getattr(self, "agv_free_move", False)
                                and agent.type == AgentType.AGV)
                if (agent.type != AgentType.PICKER and not _is_agv_move)                         or agent in commited_agents:
                    continue
                if agent.req_action != Action.FORWARD:
                    continue
                # COMMITTED ONLY (`env.picker_free_move = "committed"`, USER RULE): release the picker
                # only when its rendezvous is LIVE -- an AGV is already parked at the destination pod
                # waiting to load. That is the case the rule was designed for. Releasing every picker
                # every tick instead lets them roam, and since pickers share corridors with AGVs (both
                # collision layers are obstacles in find_path) the extra picker traffic blocks AGVs.
                if _committed_only and not _is_agv_move:
                    _pth = getattr(agent, "path", None)
                    if not _pth:
                        continue
                    _gx, _gy = _pth[-1]
                    _aid = self.grid[CollisionLayers.AGVS, _gy, _gx]
                    if not _aid:
                        continue                       # nobody waiting there -- no urgency
                    _a = self.agents[_aid - 1]
                    if _a.carrying_shelf is not None or _a.req_action != Action.TOGGLE_LOAD:
                        continue                       # present but not waiting to load
                tx, ty = agent.req_location(self.grid_size)
                if (tx, ty) in taken:
                    continue
                # FINAL STEP IS ABSOLUTE (`env.picker_final_step`, USER RULE 2026-08-08): a picker one
                # cell from its rendezvous goes IN, full stop; everyone else waits and re-decides next
                # tick. This also fixes a real bug in the check below -- the rendezvous cell IS the
                # waiting AGV's cell (picker and AGV must CO-OCCUPY to load; `_execute_load` reads
                # grid[PICKERS] at the AGV's own position), so treating the AGV layer as an obstacle
                # refused the one move the picker exists to make. Every picker, every time.
                _final = (getattr(self, "picker_final_step", False)
                          and not _is_agv_move
                          and len(getattr(agent, "path", None) or []) == 1)
                if self.grid[CollisionLayers.PICKERS, ty, tx]:
                    continue                       # another picker is there -- genuine collision
                if self.grid[CollisionLayers.AGVS, ty, tx] and not _final:
                    continue                       # an AGV is there and this is not the rendezvous
                commited_agents.add(agent)
                taken.add((tx, ty))
        failed_agents = set(agent_list) - commited_agents
        for agent in failed_agents:
            agent.req_action = Action.NOOP
        return clashes

    def resolve_stuck_agents(self) -> None:
        # This can happen when their goal is occupied after reaching their last step/re-calculating a path
        overall_stucks = 0
        moving_agents = [
            agent
            for agent in self.agents
            if agent.busy
            and agent.req_action not in (Action.LEFT, Action.RIGHT) # Don't count changing directions
            and (agent.req_action!=Action.TOGGLE_LOAD or (agent.x, agent.y) in self.goals) # Don't count loading or changing directions / if at goal
        ]
        for agent in moving_agents:
            agent_stuck_count = self.stuck_counters[agent.id - 1]
            agent_stuck_count.update((agent.x, agent.y))
            if _STUCK_THRESHOLD < agent_stuck_count.count < _STUCK_THRESHOLD + self.column_height + 2:  # Time to get out of aisle
                agent.req_action = Action.NOOP
                if agent.path:
                    new_path = self.find_path((agent.y, agent.x), (agent.path[-1][1], agent.path[-1][0]), agent)
                    # Picker should wait for AGV to arrive at destination regardless of stuck count
                    if new_path:
                        # LIVELOCK FIX (2026-08-05). This reset used to be unconditional, so a futile
                        # replan loop capped the counter at _STUCK_THRESHOLD+1 forever (replan -> reset
                        # -> still can't move -> replan ...) and the release below (busy=False) was
                        # UNREACHABLE: agents held a task + path + busy=True to the end of the episode.
                        # Now a fresh stuck-budget is granted only when the replan actually produced a
                        # DIFFERENT route; a futile replan lets the counter climb to the release.
                        # NB this is a partial fix -- the ROOT cause is upstream in
                        # resolve_move_conflict, which silences every agent outside commited_agents.
                        same_path = (new_path == agent.path)
                        agent.path = new_path
                        if len(agent.path) == 1:
                            continue
                        if not same_path:
                            agent_stuck_count.reset((agent.x, agent.y))
                        continue
                else:
                    overall_stucks += 1
                    agent.busy = False
                    agent_stuck_count.reset()
            if agent_stuck_count.count > _STUCK_THRESHOLD + self.column_height + 2:  # Time to get out of aisle
                overall_stucks += 1
                agent_stuck_count.reset((agent.x, agent.y))
                agent.req_action = Action.NOOP
                agent.busy = False
                if not hasattr(self, "_recently_stuck"):
                    self._recently_stuck = set()
                self._recently_stuck.add(agent.id)   # -> route around robots on the next repath
        return overall_stucks

    def _execute_forward(self, agent: Agent) -> None:
        agent.x, agent.y = agent.req_location(self.grid_size)
        agent.path = agent.path[1:]
        if agent.carrying_shelf:
            agent.carrying_shelf.x, agent.carrying_shelf.y = agent.x, agent.y
        # M2 enforcement: entering debris costs a recovery hold (collision-cost axis).
        # debris_hold_steps = -1 -> stuck UNTIL AMNESTY (as long as the debris persists).
        _dhs = getattr(self, "debris_hold_steps", 0)
        if _dhs and (agent.y, agent.x) in getattr(self, "disturbed", ()):
            if _dhs < 0:
                agent._debris_stuck = True
            else:
                agent._debris_hold = int(_dhs)
            self._debris_hits = getattr(self, "_debris_hits", 0) + 1

    def _execute_rotation(self, agent: Agent) -> None:
        agent.dir = agent.req_direction()

    def _execute_load(self, agent: Agent, rewards: np.ndarray[int]) -> np.ndarray[int]:
        shelf_id = self.grid[CollisionLayers.SHELVES, agent.y, agent.x]
        picker_id = self.grid[CollisionLayers.PICKERS, agent.y, agent.x]
        if shelf_id:
            # ORACLE (pickers_free): a picker is always present when needed -> AGV loads instantly on
            # arrival, zero picker wait (travel AND contention). Measures the picker-unconstrained ceiling.
            if (
                (agent.type == AgentType.AGV and (picker_id or getattr(self, "pickers_free", False)))
                or agent.type == AgentType.AGENT
            ):
                agent.carrying_shelf = self.shelfs[shelf_id - 1]
                self.grid[CollisionLayers.SHELVES, agent.y, agent.x] = 0
                self.grid[CollisionLayers.CARRIED_SHELVES, agent.y, agent.x] = shelf_id
                agent.busy = False
                # PICKER SERVICE TIME (opt-in `env.picker_service_steps`, 2026-08-06). The handoff was
                # INSTANTANEOUS: picker and AGV meet, the shelf transfers, and the picker is free the
                # same tick. So the one operation a picker exists to perform cost nothing -- its
                # throughput was effectively infinite and only its TRAVEL was ever priced. That matters
                # because picker rendezvous is already 75% of all lost value: the measured bottleneck
                # had a free service. RB-KAIROS+ is a mobile base + UR arm; a pick-and-place cycle for
                # that arm class is ~5-10 s, i.e. ~6-12 steps at ~0.8 s/step.
                _psvc = getattr(self, "picker_service_steps", 0.0)
                if _psvc:
                    if not hasattr(self, "_service_until"):
                        self._service_until = {}
                    _pid = picker_id if picker_id else agent.id
                    self._service_until[_pid] = self._cur_steps + int(round(_psvc))
                    self._service_until[agent.id] = self._cur_steps + int(round(_psvc))
                # AMNESTY AT THE POD (opt-in via `env.amnesty_at_pick`, 2026-08-05).
                # The Stow paper's 3.7% is per STOW ATTEMPT -- "robotic packing of items INTO fabric
                # pods", where amnesty is "the grasped item or an item already in the pod falling to
                # the floor". That event happens AT THE POD. We had attached that rate only to the
                # DELIVERY at the goal, i.e. a pod-side rate on a station-side event.
                # This is the pod-side handling event: the picker loading the shelf. Debris here
                # lands on the AISLE cells serving the shelf, so it can block ACCESS TO THE POD --
                # a much sharper cost mechanism than an obstruction on open station floor, and the
                # realistic one. Same calibrated rate, correct location; no new assumption.
                if getattr(self, "amnesty_at_pick", False):
                    _arng = getattr(self, "_disturb_rng", None)
                    if _arng is not None and getattr(self, "disturb_amnesty_rate", 0.0):
                        self.spawn_amnesty((agent.y, agent.x), self._cur_steps, _arng)
                # Reward picker for loading
                if self.reward_type == RewardType.GLOBAL:
                    rewards += 0.5
                elif self.reward_type == RewardType.INDIVIDUAL:
                    if agent.type == AgentType.AGENT:
                        rewards[agent.id - 1] += 0.1
                    else:
                        rewards[picker_id - 1] += 0.1
        else:
            agent.busy = False
        return rewards

    def _execute_unload(self, agent: Agent, rewards: np.ndarray[int]) -> np.ndarray[int]:
        if (agent.x, agent.y) in self.goals or self.grid[CollisionLayers.SHELVES, agent.y, agent.x] != 0:
            agent.busy = False
            return rewards
        picker_id = self.grid[CollisionLayers.PICKERS, agent.y, agent.x]
        # FREE POD RETURN (opt-in `env.free_pod_return`, 2026-08-08).
        # Upstream TA-RWARE (tarware/warehouse.py:554) lets an AGV put a pod back into storage ONLY
        # while a picker stands on that exact cell. If no picker is ever dispatched to the return
        # rendezvous, the AGV requests TOGGLE_LOAD every step for the rest of the episode and the
        # unload silently does nothing -- it holds the pod forever, busy and unreachable.
        # MEASURED (seed 100, peak demand, t=460-462): AGVs 1 and 6 parked on storage cells (7,1) and
        # (8,3) with no picker present, requesting TOGGLE_LOAD on every step to the end of the episode.
        # The other six AGVs were each co-located with a picker and had unloaded normally. Episode
        # delivered 1 order. This is the peak-demand "deadlock": not a blocked corridor but robots
        # stranded holding pods. It explains why the WIP cap helped monotonically (fewer carriers ->
        # fewer strandings) while extra stations and wider aisles did nothing at all.
        # The picker requirement is also unphysical for this class of system: a Kiva drive unit lifts
        # and lowers pods autonomously, and the picker exists to transfer ITEMS. Setting a pod down is
        # a drive-unit operation. With the flag, an AGV may lower a pod into an empty storage slot
        # unaided; the picker is still required for the PICK, which is the real rendezvous constraint.
        if getattr(self, "free_pod_return", False) and agent.type == AgentType.AGV:
            picker_id = picker_id or agent.id
        if not self._is_highway(agent.x, agent.y):
            if (
                (agent.type == AgentType.AGV and picker_id)
                or agent.type == AgentType.AGENT
            ):
                self.grid[CollisionLayers.SHELVES, agent.y, agent.x] = agent.carrying_shelf.id
                self.grid[CollisionLayers.CARRIED_SHELVES, agent.y, agent.x] = 0
                agent.carrying_shelf = None
                agent.busy = False
                agent.has_delivered = False
                # Reward picker for unloading
                if self.reward_type == RewardType.GLOBAL:
                    rewards += 0.5
                elif self.reward_type == RewardType.INDIVIDUAL:
                    if agent.type == AgentType.AGENT:
                        rewards[agent.id - 1] += 0.1
                    else:
                        rewards[picker_id - 1] += 0.1
        return rewards

    def execute_micro_actions(self, rewards: np.ndarray[int]) -> np.ndarray[int]:
        for agent in self.agents:
            if agent.req_action == Action.FORWARD:
                self._execute_forward(agent)
            elif agent.req_action in [Action.LEFT, Action.RIGHT]:
                self._execute_rotation(agent)
            elif agent.req_action == Action.TOGGLE_LOAD:
                if not agent.carrying_shelf:
                    rewards = self._execute_load(agent, rewards)
                else:
                    rewards = self._execute_unload(agent, rewards)
        return rewards

    def process_shelf_deliveries(self, rewards: np.ndarray[int]) -> np.ndarray[int]:
        shelf_deliveries = 0
        self.deliveries_this_step = []  # (shelf_id, agv_id) delivered this step
        self.fulfilled_this_step = []   # Order objects fulfilled this step (demand-stream mode)
        for y, x in self.goals:
            shelf_id = self.grid[CollisionLayers.CARRIED_SHELVES, x, y]
            if not shelf_id:
                continue
            _sh = self.shelfs[shelf_id - 1]
            if _sh not in self.request_queue:
                # ORDERED-WHILE-IN-TRANSIT (fixed 2026-08-24). DemandModel._refresh deliberately
                # keeps a carried shelf OUT of the dispatch queue so no second AGV is sent after a
                # pod that is off the floor -- and promises the trip already underway will serve
                # those orders. This gate broke that promise: the pod arrived, was not "requested",
                # and was refused service, orphaning the order (no robot will re-fetch it either)
                # and parking the carrier on the station forever. Seed 125 stream froze two robots
                # this way for the last ~110 steps. The queue is a DISPATCH structure, not a
                # fulfilment ledger: serve any pod that actually carries pending orders.
                _dm = getattr(self, "demand_model", None)
                if _dm is None or not _dm.pending.get(_sh.id):
                    continue
            if getattr(self, "demand_model", None) is not None:
                # Demand-stream mode: this ONE trip fulfils EVERY order pending on the shelf
                # (goods-to-person batching). No resample -- new orders come from the stream.
                self.fulfilled_this_step.extend(
                    self.demand_model.fulfill(self, self.shelfs[shelf_id - 1], self._cur_steps))
            else:
                # Uniform-resample mode (always-full queue): replace delivered shelf with a random new one.
                carried_shels = [agent.carrying_shelf for agent in self.agents if agent.carrying_shelf]
                new_shelf_candidates = list(set(self.shelfs) - set(self.request_queue) - set(carried_shels)) # sort so np.random with seed is repeatable
                new_shelf_candidates.sort(key = lambda x: x.id)
                new_request = np.random.choice(new_shelf_candidates)
                self.request_queue[self.request_queue.index(self.shelfs[shelf_id - 1])] = new_request

            agent = self.agents[self.grid[CollisionLayers.AGVS, x, y] - 1]
            self.deliveries_this_step.append((int(shelf_id), int(agent.id)))
            # AMNESTY: one roll PER ITEM HANDLED at this station, not per trip. The Stow paper's 3.7%
            # is per stow ATTEMPT (per item), and goods-to-person batching means one pod trip serves
            # every order pending on that shelf -- so a pod that gets 4 items handled has ~4 chances to
            # drop one. `n_orders` is exactly that count.
            _arng = getattr(self, "_disturb_rng", None)
            _n_items = max(1, int(len(self.fulfilled_this_step) or
                                  getattr(self.shelfs[shelf_id - 1], "n_orders", 1) or 1))
            if _arng is not None and getattr(self, "disturb_amnesty_rate", 0.0):
                for _ in range(_n_items):
                    self.spawn_amnesty((y, x), self._cur_steps, _arng)
            # STATION SERVICE TIME (opt-in, 2026-08-06). Until now a delivery was INSTANTANEOUS: the
            # pod arrived and every order on it was fulfilled in the same step. Real goods-to-person
            # stations pick at 300-600 items/hour (manufacturer figures, already cited in
            # docs/FINDINGS.md), i.e. ~6-12 s per item, and the pod OCCUPIES the station for that
            # whole time. Because one pod trip serves EVERY order pending on that shelf, dwell scales
            # with the item count -- a pod serving 4 orders holds its station four times as long.
            # This is capacity, not just delay: a stalled AGV is a robot removed from the fleet, which
            # is why stations never bottlenecked before while picker rendezvous showed as 75% of loss.
            _svc = getattr(self, "station_service_steps", 0.0)
            if _svc:
                if not hasattr(self, "_service_until"):
                    self._service_until = {}
                self._service_until[agent.id] = self._cur_steps + int(round(_svc * _n_items))
            if not agent.has_delivered:
                agent.has_delivered = True
                if self.reward_type == RewardType.GLOBAL:
                    rewards += 1
                elif self.reward_type == RewardType.INDIVIDUAL:
                    rewards[agent.id - 1] += 1
            shelf_deliveries += 1

        if shelf_deliveries:
            self._cur_inactive_steps = 0
        else:
            self._cur_inactive_steps += 1

        return rewards, shelf_deliveries

    def reset(self, seed=None, options=None)-> Tuple:
        # Reset counters
        Shelf.counter = 0
        Agent.counter = 0
        self._cur_inactive_steps = 0
        self._cur_steps = 0

        # Set seed
        self.seed(seed)

        # Make the shelfs
        self.shelfs = [
            Shelf(x, y)
            for y, x in zip(
                np.indices(self.grid_size)[0].reshape(-1),
                np.indices(self.grid_size)[1].reshape(-1),
            )
            if not self._is_highway(x, y)
        ]
        self._higway_locs = np.array([(y, x) for y, x in zip(
                np.indices(self.grid_size)[0].reshape(-1),
                np.indices(self.grid_size)[1].reshape(-1),
            ) if self._is_highway(x, y)])

        # Spawn agents on higwahy locations
        agent_loc_ids = np.random.choice(
            np.arange(len(self._higway_locs)),
            size=self.num_agents,
            replace=False,
        )
        agent_locs = [self._higway_locs[agent_loc_ids, 0], self._higway_locs[agent_loc_ids, 1]]
        # and direction
        agent_dirs = np.random.choice([d for d in Direction], size=self.num_agents)
        self.agents = [
            Agent(x, y, dir_, agent_type = agent_type)
            for y, x, dir_, agent_type in zip(*agent_locs, agent_dirs, self._agent_types)
        ]

        self.stuck_counters = [StuckCounter((agent.x, agent.y)) for agent in self.agents]
        self._recalc_grid()

        self.request_queue = list(
            np.random.choice(self.shelfs, size=self.request_queue_size, replace=False)
        )
        self.observation_space_mapper.extract_environment_info(self)
        return tuple([self.observation_space_mapper.observation(agent) for agent in self.agents])

    def set_adg_plan(self, routes_by_id):
        """Enable ADG EXECUTION: drive each agent along its committed route (a list of (x,y)
        cells) in crossing-ORDER, instead of the default A*+reroute. `routes_by_id` =
        {agent_id: [cells]}. Movement only (pick/deliver still handled at leg ends by the
        normal logic). Small lateness is absorbed as waiting; collisions 0 by construction."""
        from wwm_sim.adg import build_adg
        self.adg_routes = {aid: [tuple(c) for c in r] for aid, r in routes_by_id.items()}
        _, self.adg_pred = build_adg(self.adg_routes)
        self._adg_ptr = {aid: 0 for aid in self.adg_routes}
        self._adg_left = set()                     # (agent_id, cell) departures observed
        self._adg_prev = {a.id: (a.x, a.y) for a in self.agents}
        self._adg_stall = {}                       # agent_id -> stall until this _cur_steps
        self._adg_mode = True

    def _adg_attribute(self):
        """Set each agent's micro-action toward its next committed cell, iff the ADG allows
        (predecessor at that cell has physically LEFT it) and the cell is free."""
        for a in self.agents:                      # record who left which cell since last tick
            prev = self._adg_prev.get(a.id)
            if prev is not None and prev != (a.x, a.y):
                self._adg_left.add((a.id, prev))
            self._adg_prev[a.id] = (a.x, a.y)
        occupied = {(a.x, a.y): a.id for a in self.agents}
        claimed = set()                            # no two agents into the same cell this tick
        for a in self.agents:
            a.req_action = Action.NOOP
            route = self.adg_routes.get(a.id)
            if not route:
                continue
            ptr = self._adg_ptr[a.id]
            while ptr + 1 < len(route) and (a.x, a.y) == route[ptr + 1]:
                ptr += 1                           # advance past cells already reached
            self._adg_ptr[a.id] = ptr
            if ptr + 1 >= len(route):
                continue                           # reached route end
            if self._adg_stall.get(a.id, 0) > self._cur_steps:
                continue                           # injected stall (a delay)
            nxt = route[ptr + 1]
            pred = self.adg_pred.get((a.id, nxt))
            dep_ok = (pred is None) or ((pred, nxt) in self._adg_left)
            free = (nxt not in occupied or occupied[nxt] == a.id) and nxt not in claimed
            if dep_ok and free:
                a.path = [nxt]
                a.req_action = get_next_micro_action(a.x, a.y, a.dir, nxt)
                claimed.add(nxt)

    def _step_janitor(self):
        """EARNED AMNESTY (USER DESIGN 2026-08-21): a single human cleaner, not a timer.

        The janitor is summoned by the fleet's SIGHTINGS (rumor-map evidence; with no map, spills
        are reported immediately), walks the aisles at one cell per step ignoring robot traffic
        (humans step around robots; no collision layer), mops the spill for `janitor_clean_steps`
        (default 20 ~ 20 s), and only then does the cell clear -- releasing anything stuck in it.
        Cleanup latency = discovery + travel + mopping, so remote unseen spills persist."""
        if not getattr(self, "janitor", False):
            return
        if not hasattr(self, "_jan"):
            gx, gy = self.goals[0]
            self._jan = {"x": int(gx), "y": int(gy), "clean_left": 0, "target": None,
                         "cleaned": 0, "path": [], "home": (int(gy), int(gx)),
                         "path_dest": None}
        j = self._jan
        dist = getattr(self, "disturbed", None) or set()
        rm = getattr(self, "rumor_map", None)
        if rm is not None:
            known = {c for c in dist if rm.alpha[c[0], c[1]] > 1.05}   # any sighting evidence
        else:
            known = set(dist)
        if j["clean_left"] > 0:                    # mopping
            j["clean_left"] -= 1
            if j["clean_left"] == 0:
                c = j["target"]
                if c in self.disturbed:
                    self.disturbed.discard(c)
                    self._disturb_expiry.pop(c, None)
                j["cleaned"] += 1
                j["target"] = None
                j["path"] = []
            return
        if j["target"] is not None and j["target"] not in dist:
            j["target"] = None
            j["path"] = []
        if j["target"] is None:
            if not known:
                # no reported spills: walk back to base like a normal worker (USER 2026-08-21).
                # PRE-POSITIONING (opt-in, 2026-08-23): with a style-learning rumor map, the
                # janitor's waiting spot is the LEARNED HOTSPOT instead of the fixed base --
                # the one agent with zero opportunity cost, so predicted-where can pay in
                # response time where it could not pay in robot routing.
                dest = j["home"]
                if getattr(self, "janitor_preposition", False) and rm is not None \
                        and getattr(rm, "learn_style", False) and rm.spawn_prior.max() > 0:
                    if j.get("_pre_t", -999) + 50 <= self._cur_steps:
                        j["_pre_t"] = int(self._cur_steps)
                        G = rm.hazard_smooth() * self.highways
                        iy, ix = np.unravel_index(int(np.argmax(G)), G.shape)
                        j["_pre"] = (int(iy), int(ix))
                    dest = j.get("_pre", j["home"])
                if (j["y"], j["x"]) != dest:
                    self._jan_walk(j, dest)
                return
            j["target"] = min(known, key=lambda c: abs(c[0] - j["y"]) + abs(c[1] - j["x"]))
            j["path"] = []
            j["path_dest"] = None
        ty, tx = j["target"]
        if (j["y"], j["x"]) == (ty, tx):           # arrived -> start mopping
            j["clean_left"] = int(getattr(self, "janitor_clean_steps", 20))
            return
        self._jan_walk(j, (ty, tx))

    def _jan_walk(self, j, dest):
        """One step toward dest along highways (dest itself always enterable)."""
        ty, tx = dest
        if (j["y"], j["x"]) == (ty, tx):
            return
        if j.get("path_dest") != dest:
            j["path"] = []
        if not j["path"]:                          # BFS over highways (spill cells walkable)
            from collections import deque
            H, W = self.grid_size
            hw = self.highways
            prev = {(j["y"], j["x"]): None}
            q = deque([(j["y"], j["x"])])
            while q:
                cy, cx = q.popleft()
                if (cy, cx) == (ty, tx):
                    break
                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    ny, nx = cy + dy, cx + dx
                    if (0 <= ny < H and 0 <= nx < W and (ny, nx) not in prev
                            and (hw[ny, nx] or (ny, nx) == (ty, tx))):
                        prev[(ny, nx)] = (cy, cx)
                        q.append((ny, nx))
            if (ty, tx) not in prev:
                j["target"] = None                 # unreachable (shouldn't happen on highways)
                j["path_dest"] = None
                return
            j["path_dest"] = dest
            path, cur = [], (ty, tx)
            while cur != (j["y"], j["x"]):
                path.append(cur)
                cur = prev[cur]
            j["path"] = list(reversed(path))
        ny, nx = j["path"].pop(0)
        j["y"], j["x"] = ny, nx

    def step_disturbances(self):
        """Floor blockages. TWO sources, both ONE CELL, both static until cleared:

        1. AMNESTY (`spawn_amnesty`, delivery-triggered) -- an item dropped at a station.
           CALIBRATED: 3.7% per stow attempt, Amazon Science "Stow" (arXiv:2505.04572), 100k
           production attempts. Anchored to activity and to place, so it is fleet-size-invariant and
           spatially structured around stations.
        2. RANDOM BLOCKAGE (`disturb_rate`, here) -- everything else that ends up on the floor: a
           faulted robot awaiting recovery, a dropped pallet, maintenance equipment, a spill from a
           source other than stowing.
           NOT CALIBRATED -- no public data exists (searched 2026-08-04: warehouse obstruction stats,
           robot fault/telemetry datasets, AMR reliability, MAPF warehouse benchmarks; these are
           proprietary operational metrics). The only anchor available is a mobile-robot reliability
           study reporting MTBF ~8 h, which is field/service robots and ~20 years old. Using the Stow
           throughput (224 units/h) against ~37 deliveries per 500-step episode puts 1 step ~ 2-5 s, so
           an episode is ~17-40 min and 8 h MTBF implies roughly ONE blockage per episode across the
           fleet -> disturb_rate ~ 0.002/step. TREAT AS A SWEPT ASSUMPTION, not a fitted value.

        Opt-in via env.disturb_rate>0 (and/or env.disturb_amnesty_rate>0) + env._disturb_rng.
        Disturbances are NOT predictable -> only observable (Beta rumor map)."""
        rate = getattr(self, "disturb_rate", 0.0)
        frate = getattr(self, "disturb_fault_rate", 0.0)      # faults are independent of `rate`
        rng = getattr(self, "_disturb_rng", None)
        if (not rate and not frate) or rng is None:
            return
        if not hasattr(self, "disturbed"):
            self.disturbed = set()
            self._disturb_expiry = {}
        now = self._cur_steps
        for c in [c for c, e in self._disturb_expiry.items() if e <= now]:   # despawn expired
            self.disturbed.discard(c)
            del self._disturb_expiry[c]
        H, W = self.grid_size
        # ZONE-CLUSTERED (opt-in via disturb_clustered): per-seed HOTSPOT zones (from the seeded rng)
        # so disturbances RECUR in the same areas -> spatial structure the rumor map can actually learn
        # (spill/human-flavored). Zones DIFFER per seed -> the map must re-learn each episode (no cross-
        # seed memorization). Off -> uniform-random. Schedule stays policy-independent (rng + static map).
        if getattr(self, "disturb_clustered", False) and not hasattr(self, "_disturb_zones"):
            zs = []
            for _ in range(getattr(self, "disturb_n_zones", 3)):
                for _z in range(30):
                    zy, zx = int(rng.randint(0, H)), int(rng.randint(0, W))
                    if self._is_highway(zx, zy):
                        zs.append((zy, zx)); break
            self._disturb_zones = zs
        if rate and rng.random() < rate:                                     # maybe spawn a new blob
            clustered = getattr(self, "disturb_clustered", False) and getattr(self, "_disturb_zones", None)
            _sig = getattr(self, "disturb_zone_sigma", 1.5)
            for _ in range(15):
                if clustered:                                                # sample NEAR a per-seed zone
                    zy, zx = self._disturb_zones[int(rng.randint(0, len(self._disturb_zones)))]
                    cy = min(max(int(round(zy + rng.randn() * _sig)), 0), H - 1)
                    cx = min(max(int(round(zx + rng.randn() * _sig)), 0), W - 1)
                elif getattr(self, "traffic_weighted_blockage", False) and getattr(self, "_traffic", None) is not None:
                    # ACTIVITY-ANCHORED (opt-in, 2026-08-05). Uniform-over-highways implicitly claims
                    # debris rains evenly on the floor. It does not: debris is PRODUCED BY ACTIVITY --
                    # items fall when handled, loads shed when moved, pallets fracture under traffic,
                    # equipment is left where work happened. So sample the blockage cell in proportion
                    # to recent robot-steps per cell. Amnesty is already anchored this way (it is
                    # delivery- and pick-triggered); this makes the uncalibrated random term behave
                    # the same. NB report BOTH spawn models: weighting raises the crosser count partly
                    # by construction, so the honest test is whether it moves COST, not exposure.
                    w = self._traffic * self.highways
                    tot = float(w.sum())
                    if tot <= 0:
                        cy, cx = int(rng.randint(0, H)), int(rng.randint(0, W))
                    else:
                        idx = int(np.searchsorted(np.cumsum(w.ravel()), rng.random() * tot))
                        cy, cx = int(idx // W), int(idx % W)
                else:                                                        # uniform-random
                    cy, cx = int(rng.randint(0, H)), int(rng.randint(0, W))
                if self._is_highway(cx, cy) and (cy, cx) not in self.disturbed:
                    # ONE CELL. Physics, not a choice: a spill spreads only until it reaches minimum
                    # film thickness (~1-2 mm on concrete), so area = volume / thickness -- a whole
                    # LITRE covers ~1 m^2, which is one pod-footprint cell. Dropped solid debris
                    # scatters within its own footprint plus a small bounce. Both reach full extent in
                    # seconds and then sit until cleaned. The earlier growing-blob model (4%/cell/step,
                    # unbounded) had no counterpart in reality and produced 52 blocked cells / -31.7%.
                    # Refs: TAMU pool-spreading thesis (oaktrust 1969.1/187300); PNNL "Spills on Flat
                    # Inclined Pavements" (PNNL-14577); SLOPS porous-ground model (IChemE Hazards 30).
                    dur = int(rng.randint(*getattr(self, "disturb_dur", (150, 400))))
                    if getattr(self, "janitor", False):
                        dur = 10 ** 9              # janitor mode: no timed amnesty -- someone must mop
                    cells = {(cy, cx)}
                    # MULTI-CELL EVENT (opt-in, user 2026-08-23): disturb_event_cells=(lo,hi) makes
                    # one event scatter a contiguous blob of lo..hi highway cells (pallet fracture /
                    # shed load). Default stays the physically-defended single cell.
                    _ev = getattr(self, "disturb_event_cells", None)
                    if _ev:
                        n_extra = int(rng.randint(_ev[0], _ev[1] + 1)) - 1
                        for _g in range(n_extra):
                            frontier = [(ny, nx) for (yy, xx) in cells
                                        for (ny, nx) in ((yy-1,xx),(yy+1,xx),(yy,xx-1),(yy,xx+1))
                                        if 0 <= ny < H and 0 <= nx < W and self._is_highway(nx, ny)
                                        and (ny, nx) not in self.disturbed and (ny, nx) not in cells]
                            if not frontier:
                                break
                            cells.add(frontier[int(rng.randint(0, len(frontier)))])
                    for c in cells:
                        self.disturbed.add(c)
                        self._disturb_expiry[c] = now + dur
                    self._blockage_events = getattr(self, "_blockage_events", 0) + 1
                    self._reroute_around_disturbance(cells)
                    break

    def spawn_amnesty(self, station_cell, now, rng):
        """DEBRIS ("amnesty") -- an item on the floor near a workstation, blocking until retrieved.

        CALIBRATED, not assumed. Amazon Science, "Stow: Robotic packing of items into fabric pods"
        (arXiv:2505.04572), 100,000 stow attempts in a working fulfilment centre:
            successful 86%  ·  unproductive 9.3%  ·  AMNESTY 3.7%  ·  damage 0.2%  ·  other 0.8%
        amnesty = "either the grasped item or an item already in the pod falling to the floor".
        Throughput 224 units/hour (humans 243).

        TRIGGERED BY DELIVERIES, not by a per-step probability: stowing happens AT STATIONS, so debris
        is anchored to activity and to place -- fleet-size-invariant for free, and spatially structured
        where robots already converge (the kind of structure a belief map could learn, unlike blobs
        sprinkled on random cells). One roll PER ITEM handled, since 3.7% is per stow ATTEMPT and one
        pod trip serves every order pending on that shelf.

        ONE CELL, for the same physics as any other floor debris (see step_disturbances). The only
        number the paper does NOT give is cleanup duration -- it reports no intervention or recovery
        times -- so `disturb_amnesty_dur` stays a stated assumption.
        """
        rate = getattr(self, "disturb_amnesty_rate", 0.0)
        if not rate or rng.random() >= rate:
            return
        if not hasattr(self, "disturbed"):
            self.disturbed, self._disturb_expiry = set(), {}
        H, W = self.grid_size
        sy, sx = station_cell
        lo, hi = getattr(self, "disturb_amnesty_dur", (15, 45))
        for _ in range(12):                       # land it on a nearby drivable cell
            cy = min(max(sy + int(rng.randint(-2, 3)), 0), H - 1)
            cx = min(max(sx + int(rng.randint(-2, 3)), 0), W - 1)
            if self._is_highway(cx, cy) and (cy, cx) not in self.disturbed:
                self.disturbed.add((cy, cx))
                self._disturb_expiry[(cy, cx)] = now + int(rng.randint(lo, hi))
                self._amnesty_events = getattr(self, "_amnesty_events", 0) + 1
                self._reroute_around_disturbance({(cy, cx)})
                return

    def _reroute_around_disturbance(self, cells):
        """When a disturbance spawns on an agent's current path, re-plan that agent so it avoids it.
        DISTURBANCE-AWARE ADHERENCE (opt-in, disturb_drop_adherence): a disturbance on the committed
        route invalidates that leg's congestion plan (the route was chosen to dodge ROBOTS, not this
        random blockage). So RELEASE adherence -> find_path returns the SHORTEST path around the
        disturbance instead of fighting to rejoin the blocked route. "If you can do shorter, do shorter."""
        drop = getattr(self, "disturb_drop_adherence", False)
        for a in self.agents:
            path = getattr(a, "path", None)
            if path and any((y, x) in cells for (x, y) in path):
                if drop and getattr(a, "committed_cells", None):
                    a.committed_cells = None      # release the (now-blocked) committed route
                new_path = self.find_path((a.y, a.x), (path[-1][1], path[-1][0]), a)
                # A replan is only safe for an agent that is NOT already committed to move this tick:
                # `_execute_forward` takes the MOVE from `req_action` but pops the PATH, so swapping
                # the path under a moving agent desynchronises position from path and the next step
                # asks for a cell two squares away (KeyError in `get_next_micro_action`). Freeze it
                # for this tick and let it start the new route next tick. Also reject a replan whose
                # first cell is not adjacent, for the same reason.
                # (Surfaced by `amnesty_at_pick`: spawning debris at the pod-side load event fires
                # this mid-step, while actions are already assigned. The delivery-side spawn happened
                # to sit at a point in the step where nothing was mid-move, which is why it never
                # showed up before.)
                if new_path and abs(new_path[0][0] - a.x) + abs(new_path[0][1] - a.y) == 1:
                    a.path = new_path
                    a.req_action = Action.NOOP
                    self._disturb_reroutes = getattr(self, "_disturb_reroutes", 0) + 1

    def step(
        self, macro_actions: List[int]
    ) -> Tuple[List[np.ndarray], List[float], List[bool], List[bool], Dict]:
        if getattr(self, "traffic_weighted_blockage", False):   # decaying per-cell robot-step count
            if getattr(self, "_traffic", None) is None:
                self._traffic = np.zeros(self.grid_size, dtype=np.float32)
            self._traffic *= 0.995                             # recent traffic, not all-time
            for _a in self.agents:
                self._traffic[_a.y, _a.x] += 1.0
        self.step_disturbances()                   # spawn/despawn random blockages (opt-in)
        self._step_janitor()                       # earned amnesty: a human cleaner (opt-in)
        if getattr(self, "rumor_map", None) is not None:   # fold this step's sightings into belief
            self.rumor_map.update(self, line_of_sight=getattr(self, "los_sensing", True))
        if getattr(self, "demand_model", None) is not None:
            self.demand_model.step(self, self._cur_steps)   # inject arriving orders (opt-in)
        # Attribute macro actions to agents and resolve conflicts
        if getattr(self, "_adg_mode", False):
            self._adg_attribute()                  # ADG execution: committed routes, in order
            agvs_distance_travelled = pickers_distance_travelled = 0
            clashes_count = 0                      # ADG => no collisions, no reroute needed
            stucks_count = 0
        else:
            agvs_distance_travelled, pickers_distance_travelled = self.attribute_macro_actions(macro_actions)
            clashes_count = self.resolve_move_conflict(self.agents)
            # Restart agents if they are stuck at the same position
            stucks_count = self.resolve_stuck_agents()

        rewards = np.zeros(self.num_agents)
        # Apply penalty for inactivity
        rewards -= 0.001
        # Execute micro actions
        rewards = self.execute_micro_actions(rewards)
        # Process shelf deliveries
        rewards, shelf_deliveries = self.process_shelf_deliveries(rewards)

        self._recalc_grid()
        self._cur_steps += 1
        if (
            self.max_inactivity_steps
            and self._cur_inactive_steps >= self.max_inactivity_steps
        ) or (self.max_steps and self._cur_steps >= self.max_steps):
            terminateds = truncateds = self.num_agents * [True]
        else:
            terminateds = truncateds =  self.num_agents * [False]

        self.observation_space_mapper.extract_environment_info(self)
        new_obs = tuple([self.observation_space_mapper.observation(agent) for agent in self.agents])
        info = self._build_info(
            agvs_distance_travelled,
            pickers_distance_travelled,
            clashes_count,
            stucks_count,
            shelf_deliveries,
        )
        return new_obs, list(rewards), terminateds, terminateds, info

    def _build_info(
        self,
        agvs_distance_travelled: int,
        pickers_distance_travelled: int,
        clashes_count: int,
        stucks_count:  int,
        shelf_deliveries: int,
    ) -> Dict[str, np.ndarray]:
        info = {}
        agvs_idle_time = sum([int(agent.req_action in (Action.NOOP, Action.TOGGLE_LOAD)) for agent in self.agents[:self.num_agvs]])
        pickers_idle_time = sum([int(agent.req_action in (Action.NOOP, Action.TOGGLE_LOAD)) for agent in self.agents[self.num_agvs:]])
        info["vehicles_busy"] = [agent.busy for agent in self.agents]
        info["shelf_deliveries"] = shelf_deliveries
        info["clashes"] = clashes_count
        info["stucks"] = stucks_count
        info["agvs_distance_travelled"] = agvs_distance_travelled
        info["pickers_distance_travelled"] = pickers_distance_travelled
        info["agvs_idle_time"] = agvs_idle_time
        info["pickers_idle_time"] = pickers_idle_time
        return info

    def compute_valid_action_masks(self, pickers_to_agvs=True, block_conflicting_actions=True):
        requested_items = self.get_shelf_request_information()
        empty_items = self.get_empty_shelf_information()
        carrying_shelf_info = self.get_carrying_shelf_information()
        targets_agvs = [target - len(self.goals) - 1 for target in self.targets_agvs if target > len(self.goals)]
        targets_pickers = [target - len(self.goals) - 1 for target in self.targets_pickers if target > len(self.goals)]
        # Compute valid location list for AGVs
        valid_location_list_agvs = np.array([
            empty_items if carrying_shelf else requested_items for carrying_shelf in carrying_shelf_info
        ])
        # Compute valid location list for Pickers
        if pickers_to_agvs:
            valid_location_list_pickers = np.zeros(len(self.action_id_to_coords_map) - len(self.goals))
            valid_location_list_pickers[targets_agvs] = 1
        else:
            valid_location_list_pickers = requested_items
        # Mask out conflicting actions for agents of the same type
        if block_conflicting_actions:
            valid_location_list_agvs[:, targets_agvs] = 0
            valid_location_list_pickers[targets_pickers] = 0
        valid_action_masks = np.ones((self.num_agents, self.action_size))
        valid_action_masks[:self.num_agvs,  1 + len(self.goals):] = valid_location_list_agvs
        valid_action_masks[:self.num_agvs,  1 : 1 + len(self.goals)] = np.repeat(np.expand_dims(np.array(carrying_shelf_info), 1), len(self.goals), axis=1)
        valid_action_masks[self.num_agvs:,  1 + len(self.goals):] = valid_location_list_pickers
        valid_action_masks[self.num_agvs:,  1 : 1 + len(self.goals)] = 0
        return valid_action_masks

    def render(self, mode="human"):
        if not self.renderer:
            from wwm_sim.rendering import Viewer
            self.renderer = Viewer(self.grid_size)
        return self.renderer.render(self, return_rgb_array=mode == "rgb_array")

    def close(self):
        if self.renderer:
            self.renderer.close()

    def seed(self, seed=None):
        np.random.seed(seed)
        random.seed(seed)
